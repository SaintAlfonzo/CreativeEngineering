#!/usr/bin/env python3
"""Generate the cooking mirror of the Creative Delight scratch test suite (feature_writeup/creative_delight.md,
tests CDT-; scratch queue SQ-CDT).

Copies real single-line helper calls (`R.<helper>(...)`) from the pack's cooking scripts
(kubejs/server_scripts/cooking/*.js), unchanged, into
suite/data/creativedelight/kubejs/_cdtest/cdtest_cooking_mirror.js, inside `global.CD.recipes(() => { ... })`.
The pack keeps its own copy of each line, so every mirrored recipe has a twin: the same path under
`creativeengineering:` (the pack's line) and under `creativedelight:` (the CD copy). `/cdtest mirror` compares the
two (type, result, ingredients). That is the test of "existing cooking KubeJS on the new system": the same calls,
run from a CD script tree through the moved helpers, give the same recipes with only the namespace changed.

A line is taken only if it is one complete call whose free identifiers are all known in a CD script (R, i, f, e,
Item, Fluid, Ingredient, global and literals), so it runs unchanged outside its file. Calls that change pack
recipes (remove, replaceInput, replaceOutput) are never taken. At most --per-helper lines per helper (default 2),
the first ones in file order, so the output changes only when the cooking scripts do.

  python3 tools/creative_delight_test/gen_cdtest_mirror.py            write the file
  python3 tools/creative_delight_test/gen_cdtest_mirror.py --check    exit 1 if the file is stale
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
COOKING = os.path.join(ROOT, 'kubejs', 'server_scripts', 'cooking')
OUT = os.path.join(HERE, 'suite', 'data', 'creativedelight', 'kubejs', '_cdtest', 'cdtest_cooking_mirror.js')

NEVER = {'remove', 'replaceInput', 'replaceOutput', 'bulk', 'cfg', 'toId', 'withNamespace', 'ns'}
KNOWN = {'R', 'i', 'f', 'e', 'Item', 'Fluid', 'Ingredient', 'global', 'undefined', 'null', 'true', 'false'}
CALL = re.compile(r'^\s*R\.([A-Za-z]+)\(')
STRING = re.compile(r"'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"|`(?:\\.|[^`\\])*`")
IDENT = re.compile(r'(?<![.\w$])([A-Za-z_$][\w$]*)')


def one_call(line):
    """The call text if the line is exactly one complete R.<fn>(...) call (trailing ; and // comment allowed)."""
    stripped = STRING.sub(lambda m: '_' * len(m.group(0)), line)
    cut = stripped.find('//')
    text = line if cut < 0 else line[:cut]
    text = text.rstrip().rstrip(';').rstrip()
    masked = STRING.sub(lambda m: '_' * len(m.group(0)), text)
    depth = 0
    for n, ch in enumerate(masked):
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
            if depth == 0 and n != len(masked) - 1 and ch == ')' and masked[n + 1:].strip():
                # something after the call closes: chained (.id(...)) or two statements
                return None
    return text.strip() if depth == 0 and masked.endswith(')') else None


def free_names(call):
    masked = STRING.sub("''", call)
    masked = re.sub(r'\b\d+(\.\d+)?\b', '0', masked)
    # object keys `{ exp: 0.1 }` are not free names
    masked = re.sub(r'([{,]\s*)([A-Za-z_$][\w$]*)\s*:', r'\1:', masked)
    return set(IDENT.findall(masked)) - KNOWN


def collect(per_helper):
    picked, counts = [], {}
    for name in sorted(os.listdir(COOKING)):
        if not name.endswith('.js'):
            continue
        with open(os.path.join(COOKING, name), encoding='utf8') as fh:
            for lineno, line in enumerate(fh, 1):
                m = CALL.match(line)
                if not m or m.group(1) in NEVER or counts.get(m.group(1), 0) >= per_helper:
                    continue
                call = one_call(line)
                if not call or free_names(call):
                    continue
                counts[m.group(1)] = counts.get(m.group(1), 0) + 1
                picked.append((name, lineno, m.group(1), call))
    return picked


def render(picked):
    out = [
        '// GENERATED by tools/creative_delight_test/gen_cdtest_mirror.py - do not edit; rerun it after the cooking',
        '// scripts change. Scratch-test suite only (tools/creative_delight_test/README.md), never in the pack or a',
        '// release jar.',
        '//',
        '// Real helper calls from kubejs/server_scripts/cooking/, unchanged, run from Creative Delight\'s script tree',
        '// inside global.CD.recipes(): each recipe they make is creativedelight:<path>, the twin of the pack\'s',
        '// creativeengineering:<path>. /cdtest mirror compares every twin.',
        '',
        '// One row per mirrored call: the probe reports them and counts the twins.',
        'global.cdtestMirror = [',
    ]
    for name, lineno, fn, _ in picked:
        out.append(f"\t{{ file: '{name}', line: {lineno}, helper: '{fn}' }},")
    out += [
        ']',
        '',
        'ServerEvents.recipes(e => {',
        '\tvar i = global.item',
        '\tvar f = global.fluid',
        '\tvar R = global.NCH',
        '\tglobal.CD.recipes(() => {',
    ]
    for name, lineno, fn, call in picked:
        out.append(f'\t\t// {name}:{lineno}')
        out.append(f'\t\t{call}')
    out += [
        '\t})',
        "\tconsole.info('[cdtest] cooking mirror: ' + global.cdtestMirror.length + ' calls run under ' + R.ns() + ' after the block')",
        '})',
        '',
    ]
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--per-helper', type=int, default=2)
    args = ap.parse_args()
    picked = collect(args.per_helper)
    text = render(picked)
    if args.check:
        current = open(OUT, encoding='utf8').read() if os.path.isfile(OUT) else ''
        if current != text:
            print(f'{os.path.relpath(OUT, ROOT)} is stale: rerun tools/creative_delight_test/gen_cdtest_mirror.py')
            return 1
        print('cooking mirror up to date')
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf8') as fh:
        fh.write(text)
    helpers = sorted({fn for _, _, fn, _ in picked})
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(picked)} calls, {len(helpers)} helpers: {", ".join(helpers)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
