#!/usr/bin/env python3
"""List every loading screen tip, by resource pack, into feature_writeup/loading_tips_list.md.

Reads the built-in tip packs in Creative Common (resourcepacks/<folder>/: pack.mcmeta, CREDITS.txt if present,
assets/<namespace>/loading_tips/*.json). Run from the instance root after editing any tips.json:

    python3 tools/loading_tips_md.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKS = ROOT / "development/creativeCommon/src/main/resources/resourcepacks"
OUT = ROOT / "feature_writeup/loading_tips_list.md"


def pack_tips(pack):
    files = sorted(pack.glob("assets/*/loading_tips/*.json"))
    out = []
    for f in files:
        data = json.loads(f.read_text(encoding="utf-8"))
        out.append((f.relative_to(pack).as_posix(), bool(data.get("replace", False)), data.get("tips", [])))
    return out


def main():
    packs = sorted(p for p in PACKS.iterdir() if (p / "pack.mcmeta").is_file())
    lines = [
        "# Loading screen tips, by pack",
        "",
        "Generated by `tools/loading_tips_md.py` from Creative Common's built-in tip packs",
        "(`development/creativeCommon/src/main/resources/resourcepacks/`). Do not edit by hand: edit the pack's",
        "`tips.json` and run the script again. How the tips are shown: [loading_tips.md](loading_tips.md).",
        "",
    ]
    summary, body = [], []
    for pack in packs:
        meta = json.loads((pack / "pack.mcmeta").read_text(encoding="utf-8"))["pack"]
        files = pack_tips(pack)
        count = sum(len(t) for _, _, t in files)
        name = meta["description"].split(":")[0]
        summary.append(f"| {name} | `{pack.name}` | {count} |")
        body += [f"## {name}", "", meta["description"], ""]
        if (pack / "CREDITS.txt").is_file():
            body += [f"Attribution: `resourcepacks/{pack.name}/CREDITS.txt`.", ""]
        for path, replace, tips in files:
            body += [f"`{path}`" + (" (replace: true)" if replace else "") + f", {len(tips)} tips", ""]
            body += [f"{i}. {t}" for i, t in enumerate(tips, 1)] if tips else ["(no tips yet)"]
            body.append("")
    lines += ["| Pack | Folder | Tips |", "|---|---|---|", *summary, ""]
    lines += body
    OUT.write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(packs)} packs")


if __name__ == "__main__":
    main()
