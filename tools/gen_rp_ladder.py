"""The pack's diet ladder for Spice of Life: Raspberry Pie Addition (plan_rp_standalone.md P7, D10; raspberry_pie.md 3).

Reads the effect list kubejs/generation_scripts/food/rp_ladder.csv (sub-ladder, position, effect, level, toggle,
tagline, status) and the spacing config kubejs/generation_scripts/food/rp_ladder.json (densityRatio and the sub-ladder
spans); writes
  defaultconfigs/solraspberrypie/ladder.json                 the pack ladder (seeds each new world's serverconfig copy)
  configs_edited/server_config/solraspberrypie/ladder.json   the same file (the configs_edited backup)
  kubejs/assets/solraspberrypie/lang/en_us.json              the hover taglines, one lang key per tagline

Spacing: unlockables and permanent effects are spaced with a linearly falling density (D10): the first stretch holds
densityRatio times the effects per diversity point of the last one, endpoints fixed; a position is the inverse of the
cumulative density at equally spaced points. Hearts, the toughness / knockback pairs and the effect slots are evenly
spaced. A CSV row with status "reserved" (its effect has no id yet, or cannot be used yet) keeps its position, so the
other thresholds do not move when it is filled, and is left out of the file. A grouped heading (the group column) is
one position holding several unlocks.

    python3 tools/gen_rp_ladder.py           write the three files, print the positions
    python3 tools/gen_rp_ladder.py --check   exit 1 if a written file is stale
"""
import argparse
import csv
import json
import math
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / 'kubejs/generation_scripts/food/rp_ladder.csv'
CONFIG = ROOT / 'kubejs/generation_scripts/food/rp_ladder.json'
LADDER = ROOT / 'defaultconfigs/solraspberrypie/ladder.json'
BACKUP = ROOT / 'configs_edited/server_config/solraspberrypie/ladder.json'
LANG = ROOT / 'kubejs/assets/solraspberrypie/lang/en_us.json'

COMMENT = ('Creative Engineering pack ladder for Spice of Life: Raspberry Pie Addition (feature_writeup/raspberry_pie.md 3, '
		'plan_rp_standalone.md P7). GENERATED by tools/gen_rp_ladder.py from kubejs/generation_scripts/food/rp_ladder.csv '
		'and rp_ladder.json: edit those and rerun, not this file. Copied to <world>/serverconfig/solraspberrypie/ladder.json '
		'when a world first starts; existing worlds keep their copy (replace it there, then restart). '
		'Backup: configs_edited/server_config/solraspberrypie/ladder.json.')


def falling(n, lo, hi, ratio):
	"""n thresholds from lo to hi whose density falls linearly from ratio (start) to 1 (end), endpoints fixed."""
	if n == 1:
		return [hi]
	out = []
	total = (ratio + 1) / 2  # integral of the density ratio - (ratio - 1) x over [0, 1]
	for i in range(n):
		u = i / (n - 1) * total
		a = (ratio - 1) / 2
		if abs(a) < 1e-12:
			x = u / ratio
		else:  # ratio x - a x^2 = u, smaller root
			x = (ratio - math.sqrt(ratio * ratio - 4 * a * u)) / (2 * a)
		out.append(lo + (hi - lo) * x)
	return out


def rnd(v, decimals):
	r = round(v + 1e-9, decimals)
	return int(r) if r == int(r) else r


def read_rows():
	with open(TABLE, newline='', encoding='utf-8') as f:
		rows = list(csv.DictReader(f))
	for r in rows:
		r['position'] = int(r['position'])
		r['level'] = int(r['level'] or 1)
		r['status'] = (r['status'] or 'built').strip()
		r['toggle'] = (r['toggle'] or '').strip()
		if r['status'] not in ('built', 'reserved'):
			sys.exit(f'{TABLE.name}: {r["name"]}: status must be built or reserved, not {r["status"]!r}')
		if r['toggle'] not in ('', 'on', 'off'):
			sys.exit(f'{TABLE.name}: {r["name"]}: toggle must be empty, on or off, not {r["toggle"]!r}')
		if r['status'] == 'built' and not r['effect']:
			sys.exit(f'{TABLE.name}: {r["name"]}: a built row needs an effect id')
	return rows


def tagline_key(effect, level):
	ns, path = effect.split(':', 1)
	return f'solraspberrypie.tagline.{ns}.{path}.{level}'


def build():
	cfg = json.loads(CONFIG.read_text(encoding='utf-8'))
	ratio = float(cfg['densityRatio'])
	dec = int(cfg.get('decimals', 1))
	rows = read_rows()
	ladders = {}
	for name in ('unlock', 'permanent'):
		sub = [r for r in rows if r['ladder'] == name]
		positions = sorted({r['position'] for r in sub})
		span = cfg['unlockables' if name == 'unlock' else 'permanent']
		if positions != list(range(1, len(positions) + 1)):
			sys.exit(f'{TABLE.name}: {name} positions must run 1..n without gaps, got {positions}')
		if 'count' in span and span['count'] != len(positions):
			sys.exit(f'{TABLE.name}: {name} has {len(positions)} positions, {CONFIG.name} expects {span["count"]}')
		at = falling(len(positions), float(span['from']), float(span['to']), ratio)
		ladders[name] = (sub, {p: rnd(at[p - 1], dec) for p in positions})

	unlocks, u_at = ladders['unlock']
	perms, p_at = ladders['permanent']
	lang = {}
	pool = {}
	pool_toggle = {}
	rungs = []  # (threshold, order, rung)
	order = 0

	def add(t, rung):
		nonlocal order
		rungs.append((t, order, rung))
		order += 1

	h = cfg['hearts']
	for k in range(1, h['count'] + 1):
		add(rnd(h['top'] * k / (h['count'] + 1), dec), {'type': 'health', 'amount': h['amount']})
	p = cfg['pairs']
	for frac in p['fractions']:
		t = rnd(float(Fraction(frac)) * p['top'], dec)
		add(t, {'type': 'attribute', 'attribute': 'minecraft:generic.armor_toughness', 'amount': p['toughness']})
		add(t, {'type': 'attribute', 'attribute': 'minecraft:generic.knockback_resistance', 'amount': p['knockback']})
	sl = cfg['slots']
	for k in range(sl['count']):
		add(rnd(sl['first'] + k * (sl['top'] - sl['first']) / sl['count'], dec), {'type': 'slot'})

	for r in unlocks:
		if r['status'] != 'built':
			continue
		eff, lvl = r['effect'], r['level']
		pool[eff] = max(pool.get(eff, 1), lvl)
		if r['toggle']:
			pool_toggle[eff] = r['toggle']
		rung = {'type': 'unlock', 'effect': eff, 'level': lvl}
		if r['tagline']:
			key = tagline_key(eff, lvl)
			lang[key] = r['tagline']
			rung['tagline'] = key
		add(u_at[r['position']], rung)
	for r in perms:
		if r['status'] != 'built':
			continue
		eff, lvl = r['effect'], r['level']
		rung = {'type': 'flat', 'effect': eff, 'level': lvl}
		if r['toggle']:
			rung['toggle'] = r['toggle']
		text = r['tagline'] or next((u['tagline'] for u in unlocks if u['effect'] == eff and u['level'] == lvl and u['tagline']), '')
		if text:
			key = tagline_key(eff, lvl)
			if lang.get(key, text) != text:
				sys.exit(f'{TABLE.name}: {eff} level {lvl} has two different taglines')
			lang[key] = text
			rung['tagline'] = key
		add(p_at[r['position']], rung)

	rungs.sort(key=lambda x: (x[0], x[1]))
	pool_list = []
	for eff, cap in pool.items():
		e = {'effect': eff, 'max_level': cap}
		if eff in pool_toggle:
			e['toggle'] = pool_toggle[eff]
		pool_list.append(e)

	def line(obj):
		return json.dumps(obj, ensure_ascii=False)

	out = ['{', f'  "_comment": {line(COMMENT)},', '  "pool": [']
	out.append(',\n'.join('    ' + line(e) for e in pool_list))
	out += ['  ],', '  "rungs": [']
	out.append(',\n'.join('    ' + line({'threshold': t, **r}) for t, _, r in rungs))
	out += ['  ]', '}', '']
	ladder_text = '\n'.join(out)
	lang_text = json.dumps(dict(sorted(lang.items())), indent=2, ensure_ascii=False) + '\n'
	report = {
		'unlock': [(u_at[r['position']], r['name'], r['status']) for r in unlocks],
		'permanent': [(p_at[r['position']], r['name'], r['status']) for r in perms],
		'rungs': len(rungs), 'slots': sl['count'], 'pool': len(pool_list),
	}
	return ladder_text, lang_text, report


def main():
	ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
	ap.add_argument('--check', action='store_true', help='exit 1 if a written file is stale')
	args = ap.parse_args()
	ladder_text, lang_text, report = build()
	targets = [(LADDER, ladder_text), (BACKUP, ladder_text), (LANG, lang_text)]
	if args.check:
		stale = [str(p.relative_to(ROOT)) for p, text in targets if not p.exists() or p.read_text(encoding='utf-8') != text]
		if stale:
			print('stale (rerun python3 tools/gen_rp_ladder.py): ' + ', '.join(stale))
			return 1
		print('gen_rp_ladder: up to date')
		return 0
	for p, text in targets:
		p.parent.mkdir(parents=True, exist_ok=True)
		old = p.read_text(encoding='utf-8') if p.exists() else None
		if old != text:
			p.write_text(text, encoding='utf-8')
			print(f'wrote {p.relative_to(ROOT)}')
		else:
			print(f'unchanged {p.relative_to(ROOT)}')
	for name in ('unlock', 'permanent'):
		print(f'{name}: ' + ', '.join(f'{t} {n}' + (' (reserved)' if s == 'reserved' else '') for t, n, s in report[name]))
	print(f'Expected start line on a pack server: about {report["rungs"]} rungs, {report["slots"]} slots, {report["pool"]} pool '
		'effects (fewer when a mod is missing; those entries are skipped with one warning)')
	return 0


if __name__ == '__main__':
	sys.exit(main())
