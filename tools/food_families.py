"""Food families: every food (and every whole food block) sorted by culinary form, so cooking rules can
be written once per family instead of once per item.

A family is a form that shares a recipe shape: all jams are fruit + sugar, all pie slices come from a whole
pie, all juices are fruit pressed into a bottle. Families nest (pie/slice is in pie) like food types do. They
cut across the food types in generation_scripts/food/food_types.json, which sort by cooking state (raw,
cooked, meal) for value tuning; families sort by what the food IS, for recipe rules.

Writes four tables into feature_writeup/food_families.md (between the FAMILIES markers):
  3.1 family rules     per family: cannable, placeable, recipe shape by station, other. Each row is a Rule
                       (stated and built, with its source), Planned (a TODO row) or Decision (no stated rule:
                       a proposal to accept or change, like a can parity `?`)
  3.2 compliance       per family: members in line with each field, plus where they place and are made now
  3.3 no family        foods no family rule covers, and the items skipped on purpose
  3.4 members          every member of every family, each checked row ok / no / -

Edit FAMILIES (criteria), classify() (membership, first match wins), NO_FAMILY and RULES (the rows and their
checks). Cannable compliance reads each member's Want cell in feature_writeup/can_parity.md and the food slots
of kubejs/generation_scripts/food/can_types.json.

Also writes kubejs/generation_scripts/food/food_families.json: each family's own edible members (item ids), which
Creative Delight's creativeengineering/seasoning_tags.js turns into #creativeengineering:food_family/<path> item tags
(a parent tag holds its subfamilies) and the per-seasoning seasonable tags.

Source data: kubejs/exported/food/{catalog,foods,food_blocks,recipes,placeable}.json (/dumpfood,
/dumpplaceable), kubejs/exported/tags/item_tags.json (/dumptags item), food_types.json, placeable.json,
can_types.json, item_dict.js, can_parity.md, Supplementaries soft fluids (mods/ jars + kubejs/data).

    python3 tools/food_families.py            write the generated block
    python3 tools/food_families.py --print    print it instead
    python3 tools/food_families.py --check    change nothing; exit 1 if the block is out of date or a food is unsorted
"""
