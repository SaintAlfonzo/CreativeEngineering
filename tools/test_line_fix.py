#!/usr/bin/env python3
"""Test line form fixer and lint (design_rules.md DR-W3, plan_rules_fixes.md D12 and V-54).

The form (D12): `- [ ] **PREFIX-NN Name:** setup and action -> expected`, the colon inside the bold, a result note after
the colon. A retired id: `- [ ] ~~**PREFIX-NN Name:**~~ (moved to X)` or a short reason. `->` for arrows (D21).

What it changes, on lines that start with an indexed writeup test id (testing/test_prefix_index.md section 3):
  - adds the checkbox (`- [ ] `) to a bullet or a bold-id line that has none;
  - bolds the id and name: `ID Name: text` -> `**ID Name:** text`; with no short name before a colon, `**ID:** text`;
  - moves the colon inside the bold: `**ID Name**: text`, `**ID Name** (note): text` -> `**ID Name:** (note) text`;
  - `ID **Name:**` -> `**ID Name:**`; retired `~~ID Name~~ text`, `~~**ID Name**~~ moved to X.` -> the retired form;
  - `→` -> `->` on test lines;
  - converts `| ID | Test | Pass |` (and `| ID | Test | Expected |`) tables to test lines `- [ ] **ID:** test -> pass`.
Lines it cannot read safely are listed as ambiguous and left: an unbolded line whose id is a range, a list or prose
("VB-10 rewritten"), a note in brackets that does not close on the line, a table with another column count.

Scope: tracked feature_writeup/**/*.md except run docs and the generated queue (testing/scratch_*), archive/, todo/,
status/ and docs with generated-by headers. Code fences are skipped.

	python3 tools/test_line_fix.py              # dry run: counts per file, ambiguous lines
	python3 tools/test_line_fix.py -v           # also every change (old / new)
	python3 tools/test_line_fix.py --apply      # write the changes
	python3 tools/test_line_fix.py --lint       # exit 1 when a line would change (ambiguous lines are warnings)
	python3 tools/test_line_fix.py FILE...      # only these files
"""
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import test_prefix_lint  # noqa: E402

SKIP = re.compile(r'^feature_writeup/(testing/scratch_|archive/|todo/|status/)|\.scratch\.md$')
ID = r'[A-Z][A-Z0-9]{1,7}-\d+[a-z]?'
LINE = re.compile(r'^(?P<ind>\s*)(?P<bul>[-*] )?(?P<box>\[[ xX]\] )?(?P<rest>.*)$')
CANON = re.compile(r'^\*\*(' + ID + r')\b[^*]*:\*\*(\s|$)')
RETIRED_CANON = re.compile(r'^~~\*\*(' + ID + r')\b[^*~]*:\*\*~~(\s|$)')
# prose after an unbolded id: a range, a list, or a status word
PROSE = re.compile(r'^(' + ID + r')(\s+(to|and|or|through)\s|,|/|\s+(\(.*?\)\s+)?(is|are|was|were|passed|failed|added|'
				   r'updated|rewritten|superseded|stays|stay|moved|retired|pending|recorded|reworded|removed|dropped|'
				   r'renumbered|covers|cover|needs|need|ran|runs|open|still|now|and|as|in|on|from|fixed|kept|plus|has|have|'
				   r'never|note)\b|\s+\([^)]*\)\s*,)')
TABLE_HEAD = re.compile(r'^\|\s*ID\s*\|\s*Test\s*\|\s*(Pass|Expected)\s*\|\s*$')


def files(args):
	if args:
		return [a for a in args]
	out = subprocess.run(['git', 'ls-files', 'feature_writeup/*.md', 'feature_writeup/**/*.md'], cwd=ROOT,
						 capture_output=True, text=True).stdout.split()
	keep = []
	for p in sorted(set(out)):
		if SKIP.search(p) or not (ROOT / p).exists():
			continue
		head = (ROOT / p).read_text(encoding='utf-8', errors='replace')[:400]
		if re.search(r'generated by|Generated by|do not edit', head):
			continue
		keep.append(p)
	return keep


def close_paren(s, i):
	"""Index after the bracket group that opens at s[i] == '(', or -1 when it does not close."""
	depth = 0
	for k in range(i, len(s)):
		if s[k] == '(':
			depth += 1
		elif s[k] == ')':
			depth -= 1
			if depth == 0:
				return k + 1
	return -1


def after_bold(head, tail):
	"""`**head**` then tail -> `**head:**` and the tail with the colon moved; None when ambiguous."""
	head = head.rstrip()
	if tail.startswith(':'):
		return f'**{head}:**', tail[1:]
	t = tail.lstrip()
	if t.startswith('('):
		end = close_paren(t, 0)
		if end < 0:
			return None
		if t[end:end + 1] == ':':
			return f'**{head}:**', ' ' + t[:end] + t[end + 1:]
	return f'**{head}:**', tail


def fix_rest(rest, boxed, bulleted):
	"""Returns (new rest, None) or (None, reason) or (rest, None) when nothing to do."""
	if CANON.match(rest) or RETIRED_CANON.match(rest):
		return rest, None
	m = re.match(r'^~~\*\*(' + ID + r'\b[^*~]*?):?\*\*~~:?(.*)$', rest) or \
		re.match(r'^~~(' + ID + r'\b[^~*]*?):?~~:?(.*)$', rest) or \
		re.match(r'^\*\*~~(' + ID + r'\b[^~*]*?):?~~\*\*:?(.*)$', rest)
	if m:
		tail = m.group(2)
		mv = re.match(r'^\s*(moved to .+?)\.?\s*$', tail)
		if mv and '(' not in mv.group(1):
			tail = f' ({mv.group(1)})'
		return f'~~**{m.group(1).rstrip()}:**~~{tail}', None
	m = re.match(r'^\*\*(' + ID + r'\b[^*]*)\*\*(.*)$', rest)
	if m:
		r = after_bold(m.group(1), m.group(2))
		if r is None:
			return None, 'note in brackets does not close on the line'
		return r[0] + r[1], None
	m = re.match(r'^(' + ID + r')\s+\*\*([^*]+?)\*\*(.*)$', rest)
	if m:
		r = after_bold(f'{m.group(1)} {m.group(2).rstrip(":")}', ':' + m.group(3).lstrip(':') if
					   m.group(2).endswith(':') else m.group(3))
		if r is None:
			return None, 'note in brackets does not close on the line'
		return r[0] + r[1], None
	m = re.match(r'^(' + ID + r')\b(.*)$', rest)
	if not m:
		return rest, None
	if not (boxed or bulleted):
		return rest, None
	if PROSE.match(rest):
		return None, 'unbolded id reads as prose, a range or a list'
	tid, tail = m.group(1), m.group(2)
	if tail.startswith(':'):
		return f'**{tid}:**{tail[1:]}', None
	if tail.lstrip().startswith('('):
		r = after_bold(tid, tail)
		if r is None:
			return None, 'note in brackets does not close on the line'
		return r[0] + r[1], None
	c = re.match(r'^\s+([A-Za-z][^:`()\[\];,.>"*]{0,60}?):\s(.*)$', tail)
	if c and len(c.group(1).split()) <= 6 and '->' not in c.group(1):
		return f'**{tid} {c.group(1).rstrip()}:** {c.group(2)}', None
	return f'**{tid}:**{tail}', None


def split_cells(row):
	cells = re.split(r'(?<!\\)\|', row.strip())
	return [c.strip() for c in cells[1:-1]]


def fix_text(path, text, prefixes):
	lines = text.split('\n')
	out, changes, ambiguous = [], [], []
	fence = False
	i = 0
	while i < len(lines):
		line = lines[i]
		if line.lstrip().startswith('```'):
			fence = not fence
		if fence:
			out.append(line)
			i += 1
			continue
		if TABLE_HEAD.match(line) and i + 1 < len(lines) and re.match(r'^\|[-:| ]+\|\s*$', lines[i + 1]):
			j = i + 2
			body = []
			while j < len(lines) and lines[j].startswith('|'):
				body.append(lines[j])
				j += 1
			conv = []
			for row in body:
				c = split_cells(row)
				m = re.match(r'^(~~)?\**(~~)?(' + ID + r')\**(~~)?\**$', c[0]) if len(c) == 3 else None
				if not m:
					conv = None
					break
				test, ok = c[1].replace('\\|', '|'), c[2].replace('\\|', '|')
				body_text = f'{test} -> {ok}' if ok else test
				if m.group(1) or m.group(2):
					conv.append(f'- [ ] ~~**{m.group(3)}:**~~ {body_text}'.replace('→', '->'))
				else:
					conv.append(f'- [ ] **{m.group(3)}:** {body_text}'.replace('→', '->'))
			if conv is None:
				ambiguous.append((i + 1, 'test table with another cell count or id cell', line))
				out.extend(lines[i:j])
			else:
				changes.append((i + 1, '\n'.join(lines[i:j]), '\n'.join(conv)))
				out.extend(conv)
			i = j
			continue
		m = LINE.match(line)
		rest = m.group('rest')
		idm = re.match(r'^(?:~~)?(?:\*\*)?(?:~~)?(' + ID + r')\b', rest)
		pre = idm.group(1).rsplit('-', 1)[0] if idm else None
		if not idm or pre not in prefixes:
			out.append(line)
			i += 1
			continue
		boxed, bulleted = bool(m.group('box')), bool(m.group('bul'))
		if not boxed and len(m.group('ind')) > 1:
			out.append(line)     # a nested bullet with no checkbox is a note under a test, not a test
			i += 1
			continue
		if not boxed and not bulleted and not rest.startswith('**'):
			out.append(line)     # prose
			i += 1
			continue
		new_rest, why = fix_rest(rest, boxed, bulleted)
		if why:
			ambiguous.append((i + 1, why, line))
			out.append(line)
			i += 1
			continue
		box = m.group('box') or '[ ] '
		new = f'{m.group("ind")}- {box}{new_rest}'.replace('→', '->')
		if new != line:
			changes.append((i + 1, line, new))
		out.append(new)
		i += 1
	return '\n'.join(out), changes, ambiguous


def main():
	args = sys.argv[1:]
	apply, lint, verbose = '--apply' in args, '--lint' in args, '-v' in args
	paths = [a for a in args if not a.startswith('-')]
	rows, _queue = test_prefix_lint.read_index()
	prefixes = set(rows)
	total, amb_total, per = 0, 0, Counter()
	for p in files(paths):
		text = (ROOT / p).read_text(encoding='utf-8')
		new, changes, ambiguous = fix_text(p, text, prefixes)
		total += len(changes)
		amb_total += len(ambiguous)
		if changes:
			per[p] = len(changes)
			if verbose or lint:
				for n, old, nw in changes:
					if lint:
						print(f'{p}:{n}: off-form test line')
					else:
						print(f'{p}:{n}:\n  - {old}\n  + {nw}')
		for n, why, line in ambiguous:
			if not lint or verbose:
				print(f'AMBIGUOUS {p}:{n}: {why}: {line[:140]}')
		if apply and new != text:
			(ROOT / p).write_text(new, encoding='utf-8')
	if not lint:
		for p, n in per.most_common():
			print(f'{n:5d}  {p}')
	verb = 'changed' if apply else 'would change'
	print(f'test_line_fix: {total} line(s) {verb} in {len(per)} file(s); {amb_total} ambiguous left as written')
	if lint and total:
		sys.exit(1)


if __name__ == '__main__':
	main()
