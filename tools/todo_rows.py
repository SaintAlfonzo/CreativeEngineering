#!/usr/bin/env python3
"""TODO rows as data (plan_process_overhaul.md P3.5, rulings D13, D16, D17).

A TODO row is the only unit of work and the only place its status is written. Rows live in
feature_writeup/todo/rows/<category>.csv (one file per `#` category; legacy archive rows without a family in
rows/archive.csv). feature_writeup/todo/TODO.md is generated from them and from feature_writeup/todo/layout.md (the
headings and prose, with placeholders) by tools/status_index.py; edit rows with tools/todo.py, prose in layout.md.

Placeholders in layout.md, each on its own line:
  <?todo snapshot?>            status and tier counts
  <?todo high_priority?>       every open row with priority=high
  <?todo rows FAMILY?>         the open rows of one `##` family (FAMILY = the heading text)
  <?todo archive?>             every Complete row, then open rows without a family
  <?todo legend_status?>       the status legend table

Library: COLS, load(), save_file(), render(), row_key(), next_id(), PRIORITIES, STATUS_ORDER.
"""
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import table_io  # noqa: E402

FW = ROOT / 'feature_writeup'
TODO_DIR = FW / 'todo'
ROWS_DIR = TODO_DIR / 'rows'
LAYOUT = TODO_DIR / 'layout.md'
TODO_MD = TODO_DIR / 'TODO.md'
ARCHIVE_FILE = 'archive.csv'

COLS = ['id', 'family', 'table', 'status', 'priority', 'tests', 'work', 'change', 'details', 'decisions', 'writeup',
        'feature', 'plan', 'source', 'queue', 'log', 'updated']
STATUS_ORDER = ('Bug', 'Planned', 'Pinned', 'In Progress', 'Testing', 'Complete')
PRIORITIES = ('high', 'normal', 'low', '')
TIERS = ('S', 'C', 'P', 'T')
PLACEHOLDER_RE = re.compile(r'^<\?todo (\w+)(?: (.+?))?\?>$')
ID_RE = re.compile(r'^(.+) #(\d+)([a-z]?)$')
TABLE_HEAD = ['| Id | Change | Status | Tests | Work | Details | Decisions | Writeup |',
              '|---|---|---|---|---|---|---|---|']
GENERATED_NOTE = ('<!-- Generated by tools/status_index.py from todo/layout.md (headings, prose) and todo/rows/*.csv (rows).'
                  ' Do not edit: change rows with tools/todo.py, prose in layout.md. -->')


def slug(text):
    return re.sub(r'[^a-z0-9]+', '_', text.lower()).strip('_')


def id_parts(rid):
    m = ID_RE.match(rid or '')
    return (m.group(1), int(m.group(2)), m.group(3)) if m else (rid or '', 0, '')


def row_key(r):
    """Stable order inside a table: status rank, then id prefix, then number."""
    st = r.get('status', '')
    rank = STATUS_ORDER.index(st) if st in STATUS_ORDER else len(STATUS_ORDER)
    return (rank,) + id_parts(r.get('id'))


def category_files():
    return sorted(ROWS_DIR.glob('*.csv'))


def load():
    """[row dict] over every rows file, each with '_file' (file name)."""
    out = []
    for p in category_files():
        for d in table_io.read_dicts(p):
            d['_file'] = p.name
            out.append(d)
    return out


def save_file(name, rows):
    rows = sorted(rows, key=row_key)
    table_io.write(ROWS_DIR / name, COLS, [[r.get(c, '') for c in COLS] for r in rows])


def save_all(rows):
    by = defaultdict(list)
    for r in rows:
        by[r['_file']].append(r)
    for name, rs in by.items():
        save_file(name, rs)


def next_id(rows, family_heading):
    """D17: a new row takes the slug of its current `##` family, numbered per family."""
    s = re.sub(r'[^a-z0-9]+', '-', family_heading.lower()).strip('-')
    # numbers continue the family's old ids too: `tooling/process #10` -> the next Process row is `process #11`
    n = max([id_parts(r['id'])[1] for r in rows if id_parts(r['id'])[0].split('/')[-1] == s] + [0])
    return '%s #%d' % (s, n + 1)


def cell(text):
    return (text or '').replace('|', '\\|').replace('\n', ' ').strip()


def details_cell(r, install=None):
    d = r.get('details', '')
    if r.get('priority') == 'high':
        d = '**High priority.** ' + d
    if r.get('plan'):
        d = (d + ' Plan: %s.' % r['plan']).strip()
    if r.get('log'):
        d = (d + ' **Log:** ' + r['log']).strip()
    if install:
        d = (d + ' *Jar: %s.*' % install).strip()
    return cell(d)


def row_line(r, install=None):
    return '| `%s` | %s | %s | %s | %s | %s | %s | %s |' % (
        r['id'], cell(r.get('change')), r.get('status', ''), cell(r.get('tests')), cell(r.get('work')),
        details_cell(r, install), cell(r.get('decisions')), cell(r.get('writeup')))


def snapshot(rows):
    open_rows = [r for r in rows if r.get('family')]
    st = Counter(r['status'] for r in open_rows)
    out = ['| Status | Rows |', '|---|---|']
    for s in STATUS_ORDER:
        out.append('| %s | %d |' % (s, st.get(s, 0)))
    for s in sorted(set(st) - set(STATUS_ORDER)):
        out.append('| %s (off the legend) | %d |' % (s, st[s]))
    out.append('| **All rows with a family** | %d |' % len(open_rows))
    tiers = {t: Counter() for t in TIERS}
    none = 0
    for r in open_rows:
        if r['status'] == 'Complete':
            continue
        toks = re.findall(r'\b([SCPT])([+~]?)(?=\s|$)', r.get('tests', ''))
        if not toks:
            none += 1
        for t, mark in toks:
            tiers[t][mark or 'open'] += 1
    out += ['', 'Test tiers over the rows that are not Complete (`+` passed, `~` partly passed):', '',
            '| Tier | Passed | Partly | Open |', '|---|---|---|---|']
    for t in TIERS:
        out.append('| %s | %d | %d | %d |' % (t, tiers[t]['+'], tiers[t]['~'], tiers[t]['open']))
    arch = [r for r in rows if r['status'] == 'Complete']
    unfiled = [r for r in rows if not r.get('family') and r['status'] != 'Complete']
    pr = Counter(r.get('priority') or 'normal' for r in rows if r['status'] != 'Complete')
    out += ['', '%d rows need no tier (`none` or empty). Archive (Complete): %d rows. Open rows without a family: %d. '
            'Priority over the open rows: high %d, normal %d, low %d.' % (none, len(arch), len(unfiled), pr['high'],
                                                                         pr['normal'], pr['low'])]
    return out


def render(rows, layout_text, install_of=None):
    """TODO.md text. install_of(row) -> short install state of the row's jars, or ''."""
    install_of = install_of or (lambda r: '')
    fam = defaultdict(list)
    for r in rows:
        if r.get('family') and r['status'] != 'Complete':
            fam[r['family']].append(r)
    used = set()
    out = []
    lines = layout_text.split('\n')
    if lines and lines[0].startswith('<!-- Layout of TODO.md'):
        lines = lines[1:]
    for l in lines:
        m = PLACEHOLDER_RE.match(l.strip())
        if not m:
            out.append(l)
            continue
        kind, arg = m.group(1), (m.group(2) or '').strip()
        if kind == 'snapshot':
            out += snapshot(rows)
        elif kind == 'high_priority':
            hp = sorted((r for r in rows if r.get('priority') == 'high' and r['status'] != 'Complete'), key=row_key)
            out += TABLE_HEAD + [row_line(r, install_of(r)) for r in hp] if hp else ['No open row has high priority.']
        elif kind == 'rows':
            used.add(arg)
            rs = sorted(fam.get(arg, []), key=row_key)
            out += TABLE_HEAD + [row_line(r, install_of(r)) for r in rs] if rs else ['No open rows.']
        elif kind == 'archive':
            done = sorted((r for r in rows if r['status'] == 'Complete'), key=lambda r: id_parts(r['id']))
            out += ['| Id | Change | Work | Details | Decisions | Writeup |', '|---|---|---|---|---|---|']
            out += ['| `%s` | %s | %s | %s | %s | %s |' % (r['id'], cell(r.get('change')), cell(r.get('work')),
                                                          details_cell(r), cell(r.get('decisions')),
                                                          cell(r.get('writeup'))) for r in done]
            unf = sorted((r for r in rows if not r.get('family') and r['status'] != 'Complete'), key=row_key)
            if unf:
                out += ['', '**Open rows without a family** (P3.4 f): each goes back to its family '
                        '(`python3 tools/todo.py move ID --family "..."`) or to Complete.', ''] + TABLE_HEAD
                out += [row_line(r) for r in unf]
        else:
            out.append('<!-- unknown placeholder: %s -->' % l.strip())
    missing = sorted(set(fam) - used)
    if missing:
        out += ['', '# Rows whose family has no heading in layout.md', '']
        for f in missing:
            out += ['## %s' % f, ''] + TABLE_HEAD + [row_line(r, install_of(r)) for r in sorted(fam[f], key=row_key)] + ['']
    text = '\n'.join(out)
    return GENERATED_NOTE.replace(' -->', ' sha1=%s -->' % body_sha(text)) + '\n' + text


def body_sha(text):
    import hashlib
    return hashlib.sha1(text.encode('utf-8')).hexdigest()[:12]


def split_generated(text):
    """(recorded sha or None, body) of a rendered TODO.md."""
    first, _, body = text.partition('\n')
    m = re.search(r' sha1=([0-9a-f]+) -->$', first)
    return (m.group(1) if m else None), body


def families_in_layout(layout_text):
    return [m.group(2).strip() for m in (PLACEHOLDER_RE.match(l.strip()) for l in layout_text.split('\n'))
            if m and m.group(1) == 'rows']


def validate(rows, layout_text=None):
    """[(file, line, id, message)] schema problems."""
    errs = []
    ids = Counter(r['id'] for r in rows)
    fams = set(families_in_layout(layout_text)) if layout_text else None
    old_nums = Counter((id_parts(r['id'])[0].split('/')[-1], id_parts(r['id'])[1]) for r in rows)
    for r in rows:
        where = (r.get('_file', '?'), r.get('_line', 0), r.get('id', ''))
        pre, num, _ = id_parts(r.get('id'))
        if '/' not in pre and old_nums[(pre, num)] > 1:
            errs.append(where + ('number %d is already used by an old `.../%s` id (D17: numbers continue)' % (num, pre),))
        if not ID_RE.match(r.get('id', '')):
            errs.append(where + ('id is not `family #n`',))
        if ids[r['id']] > 1:
            errs.append(where + ('id on %d rows' % ids[r['id']],))
        if r.get('status') not in STATUS_ORDER:
            errs.append(where + ('status %r not in the legend' % r.get('status'),))
        if r.get('priority', '') not in PRIORITIES:
            errs.append(where + ('priority %r not high / normal / low' % r.get('priority'),))
        if fams is not None and r.get('family') and r['family'] not in fams:
            errs.append(where + ('family %r has no <?todo rows ...?> in layout.md' % r['family'],))
        if r.get('plan') and not all((FW / p.split()[0]).exists() for p in r['plan'].split(',') if p.strip()):
            errs.append(where + ('plan %r: no such file in feature_writeup/' % r['plan'],))
    return errs
