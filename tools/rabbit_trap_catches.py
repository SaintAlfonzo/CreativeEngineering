"""Rabbit trap catch tables by biome (feature_writeup/farming_for_blockheads.md 2.3.2, TODO mod-integration #10).

    python3 tools/rabbit_trap_catches.py           # write the data file and the writeup table
    python3 tools/rabbit_trap_catches.py --check   # print what would change, write nothing (exit 1 if anything)

Input: kubejs/exported/spawns.json (/dumpspawns), after the pack's spawn tuning. For each biome, every catchable type
(CATCHABLE, the 18 types of 2.3.1, ruling D11) in any of its natural spawn lists, with its spawn weight (summed when a
type is in more than one list) and its share of the biome's catchable weight.

Writes:
- development/creativeDelight/src/main/resources/data/farmingforblockheads/rabbit_trap/biomes.json, read by Creative
  Delight's rabbit trap for unattended catches (a change needs a :creativeDelight: rebuild and install)
- feature_writeup/farming_for_blockheads/rabbit_trap_catches.csv (one row per biome and type; a biome with no catches
  gets one row with an empty entity)

CATCHABLE mirrors the entity tag farmingforblockheads:rabbit_trap_capturable
(kubejs/data/creativedelight/kubejs/creativedelight/rabbit_trap.js); the trap also checks the tag at runtime, so a
type dropped from the tag is never rolled. Widening the list is TODO mod-integration #12.
"""
import csv
import io
import json
import sys
from pathlib import Path

INSTANCE = Path(__file__).resolve().parent.parent
SPAWNS = INSTANCE / 'kubejs/exported/spawns.json'
DATA_OUT = INSTANCE / 'development/creativeDelight/src/main/resources/data/farmingforblockheads/rabbit_trap/biomes.json'
CSV_OUT = INSTANCE / 'feature_writeup/farming_for_blockheads/rabbit_trap_catches.csv'

CATCHABLE = [
	'minecraft:rabbit', 'minecraft:chicken', 'minecraft:frog', 'minecraft:cat',
	'cozys-improved-cats:improved_cat', 'minecraft:ocelot', 'untitledduckmod:duck', 'quark:crab',
	'alexsmobs:jerboa', 'alexsmobs:platypus', 'alexsmobs:skunk', 'alexsmobs:roadrunner', 'alexsmobs:banana_slug',
	'alexsmobs:rain_frog', 'alexsmobs:mudskipper', 'alexsmobs:tasmanian_devil', 'alexsmobs:raccoon',
	'alexsmobs:warped_toad',
]


def tables(spawns):
	"""biome -> (dimensions, [(entity, weight)]), heaviest first (ties in spawn-list order)."""
	out = {}
	for biome in sorted(spawns['biomes']):
		b = spawns['biomes'][biome]
		weights = {}
		for entries in (b.get('spawners') or {}).values():
			for s in entries:
				if s['type'] in CATCHABLE and s.get('weight', 0) > 0:
					weights[s['type']] = weights.get(s['type'], 0) + s['weight']
		out[biome] = (';'.join(b.get('dimensions') or []), sorted(weights.items(), key=lambda kv: -kv[1]))
	return out


def render(t):
	data = {
		'_comment': 'Generated by tools/rabbit_trap_catches.py from the spawn dump; do not edit. Unattended rabbit trap '
					'catches by biome (farming_for_blockheads.md 2.3.2): entity -> weight.',
		'biomes': {biome: {e: w for e, w in rows} for biome, (_, rows) in t.items() if rows},
	}
	js = json.dumps(data, indent=1) + '\n'
	buf = io.StringIO()
	w = csv.writer(buf, lineterminator='\n')
	w.writerow(['biome', 'dimension', 'entity', 'spawn_weight', 'share_percent'])
	for biome, (dims, rows) in t.items():
		total = sum(x for _, x in rows)
		if not rows:
			w.writerow([biome, dims, '', '', ''])
		for e, x in rows:
			w.writerow([biome, dims, e, x, f'{100.0 * x / total:.1f}'])
	return js, buf.getvalue()


def main():
	check = '--check' in sys.argv
	if not SPAWNS.exists():
		print(f'missing {SPAWNS.relative_to(INSTANCE)}: run /dumpspawns first')
		return 2
	t = tables(json.loads(SPAWNS.read_text(encoding='utf-8')))
	js, table = render(t)
	changed = []
	for path, text in ((DATA_OUT, js), (CSV_OUT, table)):
		old = path.read_text(encoding='utf-8') if path.exists() else None
		if old != text:
			changed.append(path.relative_to(INSTANCE))
			if not check:
				path.parent.mkdir(parents=True, exist_ok=True)
				path.write_text(text, encoding='utf-8')
	with_catches = sum(1 for _, rows in t.values() if rows)
	print(f'rabbit trap catches: {with_catches} of {len(t)} biomes have catches; '
		  + (('changed: ' + ', '.join(map(str, changed))) if changed else 'no change'))
	return 1 if check and changed else 0


if __name__ == '__main__':
	sys.exit(main())
