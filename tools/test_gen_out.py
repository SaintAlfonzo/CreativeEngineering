#!/usr/bin/env python3
"""Offline test of tools/gen_out.py (creativedelight framework #7, CDT-13): python3 tools/test_gen_out.py"""
import json, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent)); import gen_out
m = Path(tempfile.mkdtemp()) / 'generators.json'
m.write_text(json.dumps({'generators': [
  {'id': 'plain', 'script': 'tools/a.py', 'outputs': ['kubejs/generation_scripts/food/x.json']},
  {'id': 'good', 'script': 'tools/b.py', 'outRoot': 'kubejs/data/creative_delight/kubejs/veggiesdelight', 'outputs': ['kubejs/data/creative_delight/kubejs/veggiesdelight/cans.js']},
  {'id': 'outside', 'script': 'tools/c.py', 'outRoot': 'kubejs/data/creative_delight/kubejs/vintagedelight', 'outputs': ['kubejs/generation_scripts/food/y.json']},
  {'id': 'badroot', 'script': 'tools/d.py', 'outRoot': 'kubejs/server_scripts'},
  {'id': 'dotdot', 'script': 'tools/e.py', 'outRoot': 'kubejs/data/creative_delight/kubejs/../../../server_scripts'}]}))
gen_out.MANIFEST = m
assert gen_out.out_root('plain', '/d') == Path('/d')
assert gen_out.out_root('good', '/d') == gen_out.INSTANCE / 'kubejs/data/creative_delight/kubejs/veggiesdelight'
for bad in ('badroot', 'dotdot', 'missing'):
    try: gen_out.out_root(bad, '/d'); raise AssertionError(bad)
    except SystemExit: pass
p = gen_out.problems(); assert len(p) == 3 and all(x.split(':')[0] in ('outside','badroot','dotdot') for x in p), p
assert gen_out.header('good').startswith('// Generated by tools/b.py (/cegen run good)')
print('gen_out tests PASSED')
