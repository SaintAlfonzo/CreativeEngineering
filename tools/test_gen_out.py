#!/usr/bin/env python3
"""Offline test of tools/gen_out.py (creativedelight framework #7, CDT-13): python3 tools/test_gen_out.py"""
import json, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent)); import gen_out
tmp = Path(tempfile.mkdtemp())
m = tmp / 'generators.json'
m.write_text(json.dumps({'generators': [
  {'id': 'plain', 'script': 'tools/a.py', 'outputs': ['kubejs/generation_scripts/food/x.json']},
  {'id': 'good', 'script': 'tools/b.py', 'outRoot': 'kubejs/data/creativedelight/kubejs/veggiesdelight', 'outputs': ['kubejs/data/creativedelight/kubejs/veggiesdelight/cans.js', 'kubejs/generation_scripts/food/record.json']},
  {'id': 'outside', 'script': 'tools/c.py', 'outRoot': 'kubejs/data/creativedelight/kubejs/vintagedelight', 'outputs': ['kubejs/data/creativedelight/kubejs/fruitsdelight/y.js']},
  {'id': 'badroot', 'script': 'tools/d.py', 'outRoot': 'kubejs/server_scripts'},
  {'id': 'dotdot', 'script': 'tools/e.py', 'outRoot': 'kubejs/data/creativedelight/kubejs/../../../server_scripts'},
  {'id': 'noroot', 'script': 'tools/f.py', 'outputs': ['kubejs/data/creativedelight/kubejs/minecraft/z.js']}],
  'handRun': [{'id': 'hand', 'script': 'tools/g.py', 'outRoot': gen_out.STARTUP_ROOT, 'outputs': [gen_out.STARTUP_ROOT]}]}))
gen_out.MANIFEST = m
assert gen_out.out_root('plain', '/d') == Path('/d')
assert gen_out.out_root('good', '/d') == gen_out.INSTANCE / 'kubejs/data/creativedelight/kubejs/veggiesdelight'
assert gen_out.out_root('hand', '/d') == gen_out.INSTANCE / gen_out.STARTUP_ROOT
for bad in ('badroot', 'dotdot', 'missing'):
    try: gen_out.out_root(bad, '/d'); raise AssertionError(bad)
    except SystemExit: pass
# pack files beside a CD root are fine; a CD-tree output outside the root or with no root is not
p = gen_out.problems(); assert len(p) == 4 and sorted(x.split(':')[0] for x in p) == ['badroot', 'dotdot', 'noroot', 'outside'], p
assert gen_out.header('good').startswith('// Generated by tools/b.py (/cdevgen run good)')
assert gen_out.header('hand').startswith('// Generated by tools/g.py (run by hand)')

# member scripts: split, write, rewrite unchanged, stale delete, hand-written file of the same name kept
kv = {'apple': 'minecraft:apple', 'bun': 'veggiesdelight:bun', 'flour': '#forge:flour', 'nothing': ''}
parts = gen_out.split_lists({'a': ['apple', 'bun', 'flour'], 'b': ['nothing'], 'c': []}, kv, 'creativeengineering')
assert parts == {'creativeengineering': {'a': ['flour'], 'b': ['nothing'], 'c': []}, 'minecraft': {'a': ['apple']},
                 'veggiesdelight': {'a': ['bun']}}, parts
gen_out.INSTANCE = tmp
root = tmp / 'kubejs/data/creativedelight/kubejs'
(root / 'fruitsdelight').mkdir(parents=True)
(root / 'fruitsdelight/x.js').write_text('// hand-written\n')
ch, st = gen_out.write_member_scripts('good', 'x', parts, root, 'Test data')
gen_root = tmp / 'kubejs/data/creativedelight/kubejs/veggiesdelight'   # 'good' has an outRoot: it wins over the default
assert sorted(p.parent.name for p in ch) == ['creativeengineering', 'minecraft', 'veggiesdelight'] and not st, (ch, st)
t = (gen_root / 'veggiesdelight/x.js').read_text().split('\n')
assert t[0].startswith('// Generated by tools/b.py') and t[1] == '// priority: 900' and t[2] == '// requires: veggiesdelight', t[:3]
assert '// requires' not in (gen_root / 'minecraft/x.js').read_text()
assert "global.CD.genPut('x', 'veggiesdelight', {" in t[4]
assert gen_out.write_member_scripts('good', 'x', parts, root, 'Test data', check=True) == ([], [])
del parts['minecraft']
ch, st = gen_out.write_member_scripts('good', 'x', parts, root, 'Test data', check=True)
assert ch == [] and [p.parent.name for p in st] == ['minecraft'] and (gen_root / 'minecraft/x.js').exists()
gen_out.write_member_scripts('good', 'x', parts, root, 'Test data')
assert not (gen_root / 'minecraft/x.js').exists() and (root / 'fruitsdelight/x.js').exists()
print('gen_out tests PASSED')
