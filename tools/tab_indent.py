#!/usr/bin/env python3
"""Tab indent for own source files (design_rules.md DR-C21, DR-C22; plan_rules_fixes.md section 16).

Converts the leading spaces of every line outside a literal to tabs, one tab per indent level, with the file's own
unit (detected per file: 4 or 2 spaces), and keeps what is left over as alignment spaces after the tabs (block comment
` * ` columns become tab + one space). Lines that start inside a string literal, a Java text block, a JS template
literal or a Python multi-line string are never touched. Trailing whitespace is stripped outside literals. Running it
twice changes nothing.

    python3 tools/tab_indent.py                      # dry run: files that would change, per language
    python3 tools/tab_indent.py --lang py --apply    # convert one language (py, js, java, gradle, json)
    python3 tools/tab_indent.py --lint               # exit 1 when a scope file still has space indent (check_all)
    python3 tools/tab_indent.py --scope              # list the scope and what is excluded, with the reason
    python3 tools/tab_indent.py -v FILE...           # only these files; -v prints every changed line

--apply writes a file only when its parse is equal before and after: `ast.dump` for Python, parsed values for JSON,
the javac parse tree for Java and Rhino's interpreter code (acorn under node for files Rhino cannot compile) for JS,
both through tools/tab_indent_check/AstFingerprint.java. Gradle has no parser here: the lexer keeps its literals
and the Gradle build is the check. A file that fails is skipped and listed.

Scope (DR-C21): tracked Java, JS, Gradle, Python and own hand-written JSON. Excluded: YAML, Markdown, game-written
configs (config/, defaultconfigs/, configs_edited/), generated files (kubejs/generation_scripts/, kubejs/exported/,
build/ folders, a file output of tools/generators.json, and a file under a folder output of it that carries a
"generated by" header), files from upstream donors (a development tree with a NOTICE-upstream-* file, upstream/
folders, *_upstream/), archives (kubejs/archive/, jar_archive/, deploy/, moved_code_backup/), JSON outside an own
namespace (creative*, moremooblooms, babymobs, vinerybackport) or written by a program (its text equals Python's
json.dumps output).
"""
import argparse
import ast
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANG = {'.py': 'py', '.js': 'js', '.mjs': 'js', '.java': 'java', '.gradle': 'gradle', '.json': 'json'}
SKIP = re.compile(r'^(kubejs/exported/|kubejs/generation_scripts/|kubejs/archive/|jar_archive/|deploy/|config/|'
                  r'defaultconfigs/|configs_edited/|\.claude/|mods/|saves/|server_mods/|client_mods/)'
                  r'|(^|/)moved_code_backup/|(^|/)build/|_upstream/|(^|/)node_modules/'
                  r'|^development/[^/]+(/members/[^/]+)?/upstream/')
OWN_NS = re.compile(r'^(creative[a-z_]*|moremooblooms|babymobs|vinerybackport)$')
NS_RE = re.compile(r'/(?:data|assets)/([^/]+)/')
MARKER = re.compile(r'(?i)\bgenerated\b.{0,80}\b(by|from)\b')
RHINO = 'mods/rhino-forge-1902.2.3-build.284.jar'
GSON = Path.home() / '.local/share/atlauncher/libraries/com/google/code/gson/gson/2.8.9/gson-2.8.9.jar'
HELPER = 'tools/tab_indent_check/AstFingerprint.java'
TAB_WIDTH = 4


# ---------------------------------------------------------------- scope

def tracked():
	out = subprocess.run(['git', 'ls-files', '-z'], cwd=ROOT, capture_output=True, check=True).stdout
	return [p for p in out.decode().split('\0') if p]


def generator_outputs():
	d = json.loads((ROOT / 'tools/generators.json').read_text(encoding='utf-8'))
	files, dirs = set(), set()
	for g in d.get('generators', []) + d.get('handRun', []):
		for o in g.get('outputs', []) + ([g['outRoot']] if g.get('outRoot') else []):
			o = o.rstrip('/')
			(files if Path(o).suffix else dirs).add(o)
	return files, dirs


def upstream_trees(paths):
	return {m.group(1) + '/' for p in paths for m in [re.match(r'(development/.+?)/NOTICE-upstream-[^/]*$', p)] if m}


def canonical_json(text):
	"""True when the text is exactly what json.dumps writes (a program wrote it, so its style is the program's)."""
	try:
		obj = json.loads(text)
	except ValueError:
		return False
	body = text.rstrip('\n')
	for indent in (1, 2, 3, 4, '\t'):
		for ascii_ in (True, False):
			for sort in (False, True):
				if json.dumps(obj, indent=indent, ensure_ascii=ascii_, sort_keys=sort) == body:
					return True
	return False


def classify(paths=None):
	"""Returns (scope list of (path, lang), excluded list of (path, reason))."""
	allp = tracked()
	up = upstream_trees(allp)
	gfiles, gdirs = generator_outputs()
	want = set(paths) if paths else None
	scope, excluded = [], []
	for p in allp:
		lang = LANG.get(Path(p).suffix)
		if not lang or (want is not None and p not in want):
			continue
		if not (ROOT / p).is_file():
			continue
		if SKIP.search(p):
			excluded.append((p, 'generated, config, archive or upstream folder'))
			continue
		tree = next((t for t in up if p.startswith(t)), None)
		if tree:
			excluded.append((p, 'upstream donor tree ' + tree))
			continue
		if p in gfiles:
			excluded.append((p, 'generator output'))
			continue
		text = (ROOT / p).read_text(encoding='utf-8', errors='replace')
		if any(p.startswith(d + '/') for d in gdirs) and MARKER.search('\n'.join(text.split('\n')[:12])):
			excluded.append((p, 'generated (header) under a generator output folder'))
			continue
		if lang == 'json':
			m = NS_RE.search('/' + p)
			if m and not OWN_NS.match(m.group(1)):
				excluded.append((p, 'JSON in a namespace that is not ours'))
				continue
			if canonical_json(text):
				excluded.append((p, 'JSON written by a program'))
				continue
		scope.append((p, lang))
	return scope, excluded


# ---------------------------------------------------------------- lexers
# Each returns (start, end_lit): per line, the state the line starts in ('code', 'comment' or 'lit') and whether its
# newline lies inside a literal. None when the file does not lex (unterminated literal or comment).

JS_REGEX_AFTER = set('(,=:[!&|?{};+-*%<>~^')
JS_REGEX_WORDS = {'return', 'typeof', 'case', 'do', 'else', 'in', 'of', 'new', 'delete', 'void', 'throw', 'yield',
                  'await', 'instanceof'}


def lex_c(text, lang):
	n = len(text)
	start, end_lit = ['code'], []
	state = 'code'          # code, line, block, str, tblock (Java/Groovy triple), tmpl (JS template), regex
	quote = ''
	tmpl = []               # JS template brace depths
	last, last_word = '', ''
	i = 0
	while i < n:
		c = text[i]
		if c == '\n':
			if state in ('line',):
				state = 'code'
			if state == 'str' and lang != 'js':
				state = 'code'  # unterminated single-line string: not valid code, leave the lines alone
			if state == 'regex':
				state = 'code'
			end_lit.append(state in ('str', 'tblock', 'tmpl'))
			start.append('lit' if state in ('str', 'tblock', 'tmpl') else 'comment' if state == 'block' else 'code')
			i += 1
			continue
		if state == 'code':
			if c in ' \t\r':
				i += 1
				continue
			two = text[i:i + 2]
			if lang != 'json' and two == '//':
				state = 'line'
				i += 2
				continue
			if lang != 'json' and two == '/*':
				state = 'block'
				i += 2
				continue
			if lang in ('java', 'gradle') and text[i:i + 3] in ('"""', "'''") and (lang == 'gradle' or c == '"'):
				state, quote = 'tblock', text[i:i + 3]
				i += 3
				continue
			if c == '"' or (c == "'" and lang != 'json'):
				state, quote = 'str', c
				i += 1
				continue
			if lang == 'js' and c == '`':
				state = 'tmpl'
				i += 1
				continue
			if lang == 'js' and c == '/' and (last == '' or last in JS_REGEX_AFTER or last_word in JS_REGEX_WORDS):
				state = 'regex'
				i += 1
				in_class = False
				while i < n and text[i] != '\n':
					ch = text[i]
					if ch == '\\':
						i += 2
						continue
					if ch == '[':
						in_class = True
					elif ch == ']':
						in_class = False
					elif ch == '/' and not in_class:
						break
					i += 1
				if i < n and text[i] == '/':
					i += 1
					state = 'code'
					last, last_word = ')', ''
				continue
			if lang == 'js' and tmpl:
				if c == '{':
					tmpl[-1] += 1
				elif c == '}':
					if tmpl[-1] == 0:
						tmpl.pop()
						state = 'tmpl'
						i += 1
						continue
					tmpl[-1] -= 1
			if c.isalnum() or c in '_$':
				j = i
				while j < n and (text[j].isalnum() or text[j] in '_$'):
					j += 1
				last_word, last = text[i:j], 'a'
				i = j
				continue
			last, last_word = c, ''
			i += 1
			continue
		if state == 'line':
			i += 1
			continue
		if state == 'block':
			if text[i:i + 2] == '*/':
				state = 'code'
				i += 2
				continue
			i += 1
			continue
		if state == 'str':
			if c == '\\':
				i += 2
				continue
			if c == quote:
				state, last, last_word = 'code', ')', ''
			i += 1
			continue
		if state == 'tblock':
			if c == '\\':
				i += 2
				continue
			if text[i:i + 3] == quote:
				state, last, last_word = 'code', ')', ''
				i += 3
				continue
			i += 1
			continue
		if state == 'tmpl':
			if c == '\\':
				i += 2
				continue
			if c == '`':
				state, last, last_word = 'code', ')', ''
				i += 1
				continue
			if text[i:i + 2] == '${':
				tmpl.append(0)
				state = 'code'
				last, last_word = '{', ''
				i += 2
				continue
			i += 1
			continue
		i += 1
	if state not in ('code', 'line') or tmpl:
		return None
	end_lit.append(False)
	return start, end_lit


def lex_py(text):
	import io
	import tokenize
	lines = text.split('\n')
	start = ['code'] * len(lines)
	end_lit = [False] * len(lines)
	try:
		for tok in tokenize.generate_tokens(io.StringIO(text).readline):
			if tok.type == tokenize.STRING and tok.start[0] != tok.end[0]:
				for r in range(tok.start[0] + 1, tok.end[0] + 1):
					start[r - 1] = 'lit'
				for r in range(tok.start[0], tok.end[0]):
					end_lit[r - 1] = True
	except (tokenize.TokenError, IndentationError, SyntaxError):
		return None
	return start, end_lit


def lex(text, lang):
	return lex_py(text) if lang == 'py' else lex_c(text, lang)


# ---------------------------------------------------------------- conversion

LEAD = re.compile(r'^[ \t]*')


def col_of(ws, tab=TAB_WIDTH):
	"""Visual column of a leading whitespace run; a tab is one indent unit of the file (4 or 2 columns)."""
	col = 0
	for ch in ws:
		col = (col // tab + 1) * tab if ch == '\t' else col + 1
	return col


def detect_unit(lines, start):
	"""2 or 4: the most common indent step between consecutive space-indented code lines (4 on a tie or no
	evidence). Tab-indented lines are left out: a tab is one level whatever the unit."""
	steps = Counter()
	prev = None
	for line, st in zip(lines, start):
		if st != 'code' or not line.strip() or '\t' in LEAD.match(line).group():
			continue
		c = col_of(LEAD.match(line).group())
		if prev is not None and c > prev:
			steps[c - prev] += 1
		prev = c
	return 2 if steps[2] > steps[4] else 4


def convert(text, lang):
	"""Returns (new_text, changed_line_numbers) or None when the file does not lex."""
	lx = lex(text, lang)
	if lx is None:
		return None
	start, end_lit = lx
	lines = text.split('\n')
	if len(start) != len(lines):
		return None
	# Already converted: tab-indented lines exist and every space run left after the tabs is under 4 (alignment).
	runs = [len(LEAD.match(l).group().lstrip('\t')) for l, s in zip(lines, start) if s != 'lit' and l.strip()]
	has_tabs = any(l.startswith('\t') for l, s in zip(lines, start) if s != 'lit')
	space_first = any(re.match(r'^[\t]* +\t', l) for l, s in zip(lines, start) if s != 'lit')
	done = has_tabs and max(runs, default=0) < 4 and not space_first
	unit = detect_unit(lines, start)
	out, changed = [], []
	for i, line in enumerate(lines):
		new = line
		if start[i] != 'lit' and not done:
			ws = LEAD.match(line).group()
			if ws and line.strip():
				col = col_of(ws, unit)
				new = '\t' * (col // unit) + ' ' * (col % unit) + line[len(ws):]
		if not end_lit[i]:
			# A line that starts inside a literal and ends outside it ends in code (the closing quote): strip it too.
			new = new.rstrip(' \t\r')
		if new != line:
			changed.append(i + 1)
		out.append(new)
	return '\n'.join(out), changed


# ---------------------------------------------------------------- checks

def check_py(old, new, path):
	try:
		a = ast.dump(ast.parse(old, path))
		compile(new, path, 'exec')
		return None if ast.dump(ast.parse(new, path)) == a else 'ast differs'
	except (SyntaxError, ValueError) as e:
		return f'parse: {e}'


def check_json(old, new):
	try:
		return None if json.loads(old, object_pairs_hook=list) == json.loads(new, object_pairs_hook=list) else 'values differ'
	except ValueError as e:
		return f'parse: {e}'


def fingerprints(mode, files):
	"""files: list of paths -> {path: sha or 'ERR ...'} from the Java helper."""
	if not files:
		return {}
	cp = [] if mode == 'java' else ['-cp', f'{ROOT / RHINO}{os.pathsep}{GSON}']
	res = {}
	for k in range(0, len(files), 400):
		out = subprocess.run(['java', *cp, str(ROOT / HELPER), mode, *files[k:k + 400]], capture_output=True,
		                     text=True).stdout
		for line in out.splitlines():
			if line.startswith('ERR '):
				p, _, why = line[4:].partition(' ')
				res[p] = 'ERR ' + why
			else:
				h, _, p = line.partition(' ')
				res[p] = h
	return res


ACORN = r'''
const a = require('internal/deps/acorn/acorn/dist/acorn');
const fs = require('fs');
const strip = (n) => {
	if (Array.isArray(n)) return n.map(strip);
	if (n && typeof n === 'object') {
		const o = {};
		for (const k of Object.keys(n)) if (!['start', 'end', 'loc', 'range'].includes(k)) o[k] = strip(n[k]);
		return o;
	}
	return n;
};
for (const p of process.argv.slice(1)) {
	try {
		const src = fs.readFileSync(p, 'utf8');
		let ast;
		try { ast = a.parse(src, {ecmaVersion: 'latest', sourceType: 'script', allowHashBang: true}); }
		catch (e) { ast = a.parse(src, {ecmaVersion: 'latest', sourceType: 'module', allowHashBang: true}); }
		console.log(require('crypto').createHash('sha256').update(JSON.stringify(strip(ast))).digest('hex') + ' ' + p);
	} catch (e) { console.log('ERR ' + p + ' ' + String(e).replace(/\n/g, ' ')); }
}
'''


def acorn_prints(files):
	if not files:
		return {}
	res = {}
	for k in range(0, len(files), 400):
		out = subprocess.run(['node', '--expose-internals', '-e', ACORN, *files[k:k + 400]], capture_output=True,
		                     text=True).stdout
		for line in out.splitlines():
			if line.startswith('ERR '):
				p, _, why = line[4:].partition(' ')
				res[p] = 'ERR ' + why
			else:
				h, _, p = line.partition(' ')
				res[p] = h
	return res


def check_batch(lang, pairs):
	"""pairs: {path: (old, new)} -> {path: None (equal) or reason}."""
	if lang == 'py':
		return {p: check_py(o, n, p) for p, (o, n) in pairs.items()}
	if lang == 'json':
		return {p: check_json(o, n) for p, (o, n) in pairs.items()}
	if lang == 'gradle':
		return {p: None for p in pairs}
	with tempfile.TemporaryDirectory() as tmp:
		olds, news = {}, {}
		for idx, (p, (o, n)) in enumerate(pairs.items()):
			ext = Path(p).suffix
			a, b = Path(tmp) / f'{idx}_old{ext}', Path(tmp) / f'{idx}_new{ext}'
			a.write_text(o, encoding='utf-8')
			b.write_text(n, encoding='utf-8')
			olds[p], news[p] = str(a), str(b)
		mode = 'java' if lang == 'java' else 'js'
		fp = fingerprints(mode, [x for p in pairs for x in (olds[p], news[p])])
		res = {}
		fallback = []
		for p in pairs:
			fo, fn = fp.get(olds[p], 'ERR none'), fp.get(news[p], 'ERR none')
			if fo.startswith('ERR') and lang == 'js':
				fallback.append(p)
			elif fo.startswith('ERR'):
				res[p] = 'parse (before): ' + fo[4:200]
			elif fo != fn:
				res[p] = 'parse differs' + (': ' + fn[4:200] if fn.startswith('ERR') else '')
			else:
				res[p] = None
		if fallback:
			ac = acorn_prints([x for p in fallback for x in (olds[p], news[p])])
			for p in fallback:
				fo, fn = ac.get(olds[p], 'ERR none'), ac.get(news[p], 'ERR none')
				if fo.startswith('ERR'):
					res[p] = 'neither Rhino nor acorn parses it: ' + fo[4:160]
				else:
					res[p] = None if fo == fn else 'acorn parse differs'
		return res


# ---------------------------------------------------------------- main

def main():
	ap = argparse.ArgumentParser()
	ap.add_argument('files', nargs='*')
	ap.add_argument('--lang', help='comma list of py, js, java, gradle, json')
	ap.add_argument('--apply', action='store_true')
	ap.add_argument('--lint', action='store_true')
	ap.add_argument('--scope', action='store_true')
	ap.add_argument('-v', action='store_true')
	a = ap.parse_args()
	langs = set(a.lang.split(',')) if a.lang else set(LANG.values())
	scope, excluded = classify(a.files or None)
	scope = [(p, l) for p, l in scope if l in langs]
	if a.scope:
		print(f'{len(scope)} files in scope: ' + ', '.join(f'{l} {n}' for l, n in Counter(l for _, l in scope).items()))
		reasons = Counter(r if not r.startswith('upstream donor tree') else 'upstream donor trees' for _, r in excluded)
		for r, n in reasons.most_common():
			print(f'  excluded {n:6d}  {r}')
		if a.v:
			for t in sorted({r for _, r in excluded if r.startswith('upstream donor tree')}):
				print('   ', t)
		return 0
	pending = {}
	unlexed = []
	for p, lang in scope:
		text = (ROOT / p).read_text(encoding='utf-8')
		r = convert(text, lang)
		if r is None:
			unlexed.append(p)
			continue
		new, changed = r
		if new != text:
			pending.setdefault(lang, {})[p] = (text, new, changed)
	if a.lint:
		bad = [(p, len(v[2])) for lang in pending for p, v in pending[lang].items()]
		for p, n in sorted(bad):
			print(f'{p}: {n} lines with space indent or trailing whitespace (python3 tools/tab_indent.py --apply {p})')
		for p in unlexed:
			print(f'{p}: does not lex (unterminated literal or comment), not checked')
		print(f'tab_indent: {len(bad)} files to convert, {len(unlexed)} not lexed, {len(scope)} in scope')
		return 1 if bad else 0
	total = 0
	skipped = []
	for lang in sorted(pending):
		files = pending[lang]
		print(f'## {lang}: {len(files)} files, {sum(len(v[2]) for v in files.values())} lines')
		if a.v:
			for p, (_, _, ch) in sorted(files.items()):
				print(f'   {p}: {len(ch)}')
		if not a.apply:
			continue
		res = check_batch(lang, {p: (o, n) for p, (o, n, _) in files.items()})
		for p, (o, n, ch) in sorted(files.items()):
			if res.get(p):
				skipped.append((p, res[p]))
				continue
			(ROOT / p).write_text(n, encoding='utf-8')
			total += 1
	for p in unlexed:
		print(f'not lexed (skipped): {p}')
	for p, why in skipped:
		print(f'check failed (skipped): {p}: {why}')
	if a.apply:
		print(f'written: {total} files; skipped: {len(skipped) + len(unlexed)}')
	return 1 if skipped else 0


if __name__ == '__main__':
	sys.exit(main())
