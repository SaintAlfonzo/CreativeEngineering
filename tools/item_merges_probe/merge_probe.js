// Scratch probe for feature_writeup/item_merges.md 2.6 (apple cider chain) and 2.7 (Froststone), queue entries
// SQ-MG-* in feature_writeup/testing/scratch_queue.md. Scratch-only: copy into a scratch server's
// kubejs/server_scripts (tools/creative_labels_test/scratch_server.sh). Results are "[mgtest] PASS|FAIL ..." lines.
//   runs once when the server has loaded, and again on /mgtest
//   /mgpf <x> <z>   counts Quark vs Immersive Weathering permafrost in the 3x3 chunks around x z, y 100-145.
//                   forceload the chunks first (vanilla /forceload add), never on ungenerated land
(() => {
    const $MGRL = Java.loadClass('net.minecraft.resources.ResourceLocation')
    const $MGForgeReg = Java.loadClass('net.minecraftforge.registries.ForgeRegistries')
    const $MGTagKey = Java.loadClass('net.minecraft.tags.TagKey')
    const $MGRegistry = Java.loadClass('net.minecraft.core.Registry')
    const $MGBlockPos = Java.loadClass('net.minecraft.core.BlockPos')
    const $MGInt = Java.loadClass('com.mojang.brigadier.arguments.IntegerArgumentType')

    function check(name, ok, detail) { console.info('[mgtest] ' + (ok ? 'PASS' : 'FAIL') + ' ' + name + ': ' + detail) }

    function idOf(st) { return String($MGForgeReg.ITEMS.getKey(st.getItem())) }

    function recipe(rm, id) {
        let opt = rm.byKey(new $MGRL(id))
        return opt.isPresent() ? opt.get() : null
    }

    // recipes of one type whose serialized json mentions every needle (ids of IE bottling are generated by NCH.toId)
    function findByJson(rm, type, needles) {
        let hits = []
        // by type, never r.getType() on every recipe: Create Mechanical Extruder's ExtrudingRecipe throws an
        // AbstractMethodError there that Rhino can't catch, and from a command it crashes the server
        rm.getAllRecipesFor($MGForgeReg.RECIPE_TYPES.getValue(new $MGRL(type))).forEach(r => {
            // ItemStack.toString has no namespace: match on registry ids (IE bottling keeps its outputs in a list)
            let s = String(r.getId())
            try { s = s + ' ' + idOf(r.getResultItem()) } catch (err) {}
            try { r.output.get().forEach(st => { s = s + ' ' + idOf(st) }) } catch (err) {}
            hits.push({ id: String(r.getId()), text: s })
        })
        return hits.filter(h => needles.every(n => h.text.indexOf(n) >= 0))
    }

    function fluidInTag(tag, fluidId) {
        let key = $MGTagKey.create($MGRegistry.FLUID_REGISTRY, new $MGRL(tag))
        let fluid = $MGForgeReg.FLUIDS.getValue(new $MGRL(fluidId))
        return fluid != null && fluid.is(key)
    }

    function run(server) {
        try {
            let rm = server.getRecipeManager()

            // SQ-MG-01: the new cider recipes parsed (a bad custom json is dropped at load, so present = parsed)
            ;['creativedelight:createmixing/long_apple_cider', 'creativedelight:createmixing/strong_apple_cider',
              'creativedelight:iemixer/apple_cider', 'creativedelight:iemixer/long_apple_cider',
              'creativedelight:iemixer/strong_apple_cider'].forEach(id => {
                let r = recipe(rm, id)
                check('SQ-MG-01 loaded ' + id, r != null, r == null ? 'missing' : String($MGForgeReg.RECIPE_SERIALIZERS.getKey(r.getSerializer())))
            })
            ;['farmersdelight:apple_cider', 'farmersrespite:long_apple_cider', 'farmersrespite:strong_apple_cider'].forEach(item => {
                let hits = findByJson(rm, 'immersiveengineering:bottling_machine', [item])
                check('SQ-MG-01 bottling ' + item, hits.length == 1, hits.map(h => h.id).join(', ') || 'none')
            })

            // SQ-MG-02: tmted's two recipes are gone, CCK's base mixing stays
            check('SQ-MG-02 removed tmted:mixer/apple_cider', recipe(rm, 'tmted:mixer/apple_cider') == null, '')
            check('SQ-MG-02 removed tmted:bottling/apple_cider', recipe(rm, 'tmted:bottling/apple_cider') == null, '')
            check('SQ-MG-02 kept create_central_kitchen:mixing/apple_cider', recipe(rm, 'create_central_kitchen:mixing/apple_cider') != null, '')

            // SQ-MG-03: one fluid per cider tag, base tag without the tiers
            check('SQ-MG-03 base tag', fluidInTag('forge:fluid/apple_cider', 'create_central_kitchen:apple_cider')
                && !fluidInTag('forge:fluid/apple_cider', 'create_central_kitchen:long_apple_cider'), '')
            check('SQ-MG-03 long tag', fluidInTag('forge:fluid/long_apple_cider', 'create_central_kitchen:long_apple_cider'), '')
            check('SQ-MG-03 strong tag', fluidInTag('forge:fluid/strong_apple_cider', 'create_central_kitchen:strong_apple_cider'), '')

            // SQ-MG-04: Froststone craft
            let fs = recipe(rm, 'creativeengineering:shapeless/froststone')
            check('SQ-MG-04 froststone recipe', fs != null && idOf(fs.getResultItem()) == 'quark:permafrost'
                && fs.getResultItem().getCount() == 2, fs == null ? 'missing' : String(fs.getResultItem()))
        } catch (err) {
            console.error('[mgtest] FAIL probe error: ' + err)
        }
    }

    ServerEvents.loaded(e => run(e.server))

    ServerEvents.commandRegistry(e => {
        const { commands: Commands } = e
        e.register(Commands.literal('mgtest').executes(ctx => { run(ctx.source.getServer()); return 1 }))
        e.register(Commands.literal('mgpf')
            .then(Commands.argument('x', $MGInt.integer())
                .then(Commands.argument('z', $MGInt.integer())
                    .executes(ctx => {
                        let x = $MGInt.getInteger(ctx, 'x')
                        let z = $MGInt.getInteger(ctx, 'z')
                        let level = ctx.source.getLevel()
                        let quark = 0, iw = 0
                        let cx = x >> 4, cz = z >> 4
                        for (let qx = (cx - 1) * 16; qx < (cx + 2) * 16; qx++)
                            for (let qz = (cz - 1) * 16; qz < (cz + 2) * 16; qz++)
                                for (let y = 100; y <= 145; y++) {
                                    let id = String($MGForgeReg.BLOCKS.getKey(level.getBlockState(new $MGBlockPos(qx, y, qz)).getBlock()))
                                    if (id === 'quark:permafrost') quark++
                                    else if (id === 'immersive_weathering:permafrost') iw++
                                }
                        console.info('[mgtest] SQ-MG-06 permafrost at ' + x + ' ' + z + ': quark ' + quark + ', immersive_weathering ' + iw)
                        return 1
                    }))))
    })
})()
