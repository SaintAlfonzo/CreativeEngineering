#!/usr/bin/env python3
"""Scan a client latest.log and write the per-mod lists of repeated resource warnings.

Usage: python3 tools/log_warnings_scan.py [log] [out]
Defaults: logs/latest.log -> feature_writeup/log_warnings_lists.md
Acknowledgements are read from feature_writeup/log_warnings_ack.txt (one `category namespace # reason` per line).
Categories: blockstate, texref, chain, missingfile, modelload.
"""
import re
import sys
from collections import defaultdict, Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "logs/latest.log"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "feature_writeup/log_warnings_lists.md"
ACK = ROOT / "feature_writeup/log_warnings_ack.txt"

RX = {
    "blockstate": re.compile(r"Exception loading blockstate definition: '([a-z0-9_.-]+):blockstates/([^']+)\.json'"),
    "texref": re.compile(r"Unable to resolve texture reference: #(missingno?|\w+) in ([a-z0-9_.-]+):(\S+)"),
    "chain": re.compile(r"Unable to resolve texture due to reference chain (\w+)->\w+ in ([a-z0-9_.-]+):(\S+)"),
    "missingfile": re.compile(r"Using missing texture, file ([a-z0-9_.-]+):(\S+) not found"),
    "modelload": re.compile(r"Unable to load model: '([a-z0-9_.-]+):([^']+)' referenced from: ([a-z0-9_.-]+):([^#:\s]+)"),
}
TITLES = {
    "blockstate": "Blockstate has a variant with no model",
    "texref": "Model uses a texture variable it never defines (#missing)",
    "chain": "Texture variable points at itself (reference chain)",
    "missingfile": "Texture file not found (ERROR level)",
    "modelload": "Model file not found",
}


def collapse(name):
    """Fold numbered / colour variants so a family prints once."""
    name = re.sub(r"_\d+$", "", name)
    return name


def load_ack():
    ack = {}
    if ACK.exists():
        for line in ACK.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            body, _, why = line.partition("#")
            parts = body.split()
            if len(parts) == 2:
                ack[(parts[0], parts[1])] = why.strip() or "acknowledged"
    return ack


def main():
    data = {k: defaultdict(Counter) for k in RX}  # category -> ns -> name -> lines
    extra = defaultdict(dict)                      # (cat, ns, name) -> detail
    for line in LOG.read_text(errors="replace").splitlines():
        if "/WARN]" not in line and "/ERROR]" not in line:
            continue
        m = RX["blockstate"].search(line)
        if m:
            data["blockstate"][m[1]][collapse(m[2])] += 1
            continue
        m = RX["texref"].search(line)
        if m:
            data["texref"][m[2]][collapse(m[3])] += 1
            extra[("texref", m[2], collapse(m[3]))]["var"] = "#" + m[1]
            continue
        m = RX["chain"].search(line)
        if m:
            data["chain"][m[2]][collapse(m[3])] += 1
            extra[("chain", m[2], collapse(m[3]))]["var"] = "#" + m[1]
            continue
        m = RX["missingfile"].search(line)
        if m:
            data["missingfile"][m[1]][m[2]] += 1
            continue
        m = RX["modelload"].search(line)
        if m:
            data["modelload"][m[3]][m[4] + " -> " + m[1] + ":" + m[2]] += 1
            continue

    ack = load_ack()
    out = [
        "# Log warning lists (generated)",
        "",
        f"Generated by `tools/log_warnings_scan.py` from `{LOG.relative_to(ROOT) if LOG.is_relative_to(ROOT) else LOG}`. "
        "Do not hand-edit; re-run after a launch. Overview and verdicts: [log_warnings.md](log_warnings.md).",
        "Acknowledged groups come from [log_warnings_ack.txt](log_warnings_ack.txt) "
        "(`category namespace # reason`, one per line).",
        "",
        "Numbered variants are folded (`chair_back_1` .. `chair_back_6` print as `chair_back`). "
        "Count = log lines, not unique models.",
        "",
        "## Totals per mod",
        "",
        "| Namespace | " + " | ".join(TITLES) + " |",
        "|---|" + "---|" * len(TITLES),
    ]
    nss = sorted({ns for c in data.values() for ns in c},
                 key=lambda n: -sum(sum(data[c][n].values()) for c in data if n in data[c]))
    for ns in nss:
        cells = []
        for c in TITLES:
            n = sum(data[c][ns].values()) if ns in data[c] else 0
            cells.append(str(n) if n else "")
        out.append(f"| {ns} | " + " | ".join(cells) + " |")
    out.append("")
    for c, title in TITLES.items():
        out += [f"## {title} (`{c}`)", ""]
        for ns in sorted(data[c], key=lambda n: -sum(data[c][n].values())):
            names = data[c][ns]
            tag = ""
            if (c, ns) in ack:
                tag = f" - ACKNOWLEDGED ({ack[(c, ns)]})"
            out.append(f"### {ns}: {sum(names.values())} lines, {len(names)} unique{tag}")
            out.append("")
            for name, n in sorted(names.items()):
                var = extra.get((c, ns, name), {}).get("var")
                out.append(f"- `{name}`" + (f" {var}" if var else "") + (f" x{n}" if n > 1 else ""))
            out.append("")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT} ({len(out)} lines)")


main()
