#!/usr/bin/env python3
"""Write kubejs/startup_scripts/compost/compost_values.js from a /dumpcompost dump.

Every item in the dump's "original" table (the composter table as vanilla + mods registered it)
becomes one row [i.<item_dict key>, <its original chance>], grouped by the compost_rules.js category
the item falls in (seeds first, same order as the rules; items no rule matches go under "other").
Items an exclusion blocks are left out and named in a comment. Ids the item dict has no key for get
one, in a generated block of item_dict.js before the Validation header.

The values file is hand-edited after the first run, so this refuses to overwrite it without --force.

  python3 tools/gen_compost_values.py [--dump kubejs/exported/compost/compost.json] [--force] [--dry-run]
"""
import argparse
import json
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from food_catalog import INSTANCE, DICT, parse_dict, best_key, new_key  # noqa: E402

OUT = INSTANCE / 'kubejs/startup_scripts/compost/compost_values.js'
DUMP = INSTANCE / 'kubejs/exported/compost/compost.json'
BLOCK_START = '// ############################## Compost items (generated by tools/gen_compost_values.py) ##############################'
BLOCK_END = '// ===== end compost items (generated) ====='


def fmt(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return s if '.' in s else s + '.0'


def dict_block(src, new_entries):
    s, e = src.find(BLOCK_START), src.find(BLOCK_END)
    old = []
    if s >= 0 and e >= 0:
        import re
        old = [(m.group(1), m.group(2)) for m in re.finditer(r"^i\.(\w+)\s*=\s*'([^']*)'", src[s:e], re.M)]
    rows = sorted(set(old) | set(new_entries), key=lambda kv: (kv[1], kv[0]))
    out = [BLOCK_START,
           '// Compostable items the dict had no key for (kubejs/startup_scripts/compost/compost_values.js).',
           '']
    by_ns = OrderedDict()
    for k, v in rows:
        by_ns.setdefault(v.split(':', 1)[0], []).append((k, v))
    for ns, group in by_ns.items():
        out.append(f'// ===== {ns} ({len(group)}) =====')
        w = max(len(k) for k, _ in group)
        out += [f"i.{k.ljust(w)} = '{v}';" for k, v in group]
        out.append('')
    out.append(BLOCK_END)
    block = '\n'.join(out)
    if s >= 0 and e >= 0:
        return src[:s] + block + src[e + len(BLOCK_END):]
    anchor = src.find('// ############################## Validation')
    if anchor < 0:
        raise SystemExit('item_dict.js: no Validation header to insert before')
    return src[:anchor] + block + '\n\n' + src[anchor:]


def render_values(groups, order, excluded):
    """groups: category -> [(item id, dict key, chance)]. Returns the compost_values.js text."""
    total = sum(len(v) for v in groups.values())
    out = [
        '// Compost values - explicit per-item chances. Started from every item that was compostable before',
        '// global.compost took over the table, at the chance vanilla or its mod gave it (generated once by',
        '// tools/gen_compost_values.py from /dumpcompost), plus hand-added items. Edit by hand from here on.',
        '//',
        '// Row: [i.<item_dict key>, chance]. Chance = a number 0-1 or a tier name from compost_rules.js',
        "// ('low' 0.3, 'medium' 0.5, 'high' 0.65, 'very_high' 0.85, 'full' 1.0); 0 = not compostable.",
        '// A row here beats the rules in compost_rules.js; its exclusions still beat a row here.',
        '// Sections follow the rule categories (the first rule an item matches), seeds first. Add a new',
        '// item to any section: the section name only groups the file and labels /dumpcompost.',
        '// After editing: /kubejs reload startup_scripts, then /reload. Engine: startup_scripts/func/compost.js.',
        f'// {total} items.',
    ]
    if excluded:
        out += ['//', '// Compostable before, now blocked by an exclusion in compost_rules.js:',
                '//   ' + ', '.join(sorted(excluded))]
    out += ['', ';(function () {', '\tvar i = global.item', '\tvar C = global.compost']
    for cat in order:
        rows = groups.get(cat)
        if not rows:
            continue
        rows.sort(key=lambda r: (r[0].split(':')[0] != 'minecraft', r[0]))
        out += ['', f"\t// ── {cat} ({len(rows)}) " + '─' * max(4, 72 - len(cat)), f"\tC.values('{cat}', ["]
        w = max(len(k) for _, k, _ in rows) + 3
        ns_prev = None
        for item_id, key, chance in rows:
            ns = item_id.split(':')[0]
            if ns != ns_prev:
                out.append(f'\t\t// {ns}')
                ns_prev = ns
            out.append(f"\t\t[{('i.' + key + ',').ljust(w)} {fmt(chance)}],")
        out.append('\t])')
    out += ['})()', '']
    return '\n'.join(out)



def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--dump', default=str(DUMP))
    ap.add_argument('--force', action='store_true', help='overwrite an existing compost_values.js')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    d = json.load(open(a.dump))
    if OUT.exists() and not a.force and not a.dry_run:
        raise SystemExit(f'{OUT.relative_to(INSTANCE)} exists (hand-edited?); pass --force to overwrite')

    src, key_val, by_id = parse_dict()
    taken = set(key_val)
    order = [c['name'] for c in d['categories']] + ['other']
    groups = defaultdict(list)
    excluded = []
    new_keys = []
    for item_id, chance in d['original'].items():
        if item_id in d['excluded']:
            excluded.append(item_id)
            continue
        info = d['now'].get(item_id)
        cat = info['category'] if info and info.get('category') in order else 'other'
        if by_id.get(item_id):
            key = best_key(item_id, by_id[item_id])
        else:
            key = new_key(item_id, taken)
            taken.add(key)
            new_keys.append((key, item_id))
        groups[cat].append((item_id, key, chance))

    out = render_values(groups, order, excluded)
    total = sum(len(v) for v in groups.values())
    print(f'{total} values in {len([c for c in order if groups.get(c)])} sections, {len(excluded)} excluded, '
          f'{len(new_keys)} new item_dict keys')
    for cat in order:
        if groups.get(cat):
            print(f'  {cat}: {len(groups[cat])}')
    if a.dry_run:
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out)
    if new_keys:
        DICT.write_text(dict_block(src, new_keys))
    print(f'wrote {OUT.relative_to(INSTANCE)}' + (f' and {len(new_keys)} keys to item_dict.js' if new_keys else ''))


if __name__ == '__main__':
    main()
