#!/usr/bin/env python3
"""Write the generated compost value files (one per mod) in Creative Delight's startup tree from a /dumpcompost dump.

Output: development/creativeDelight/src/main/resources/kubejs_startup/<namespace>/compost_values.js, one file per item
namespace (vinery and brewinandchewin go to development/creativeBrewing/src/main/resources/kubejs_startup/ since
2026-11-01) (vanilla in minecraft/), each headed `// requires: <namespace>` (none for minecraft/ and the pack's own
creativeengineering/) and marked generated. Until 2026-10-25 this wrote the single pack file
kubejs/startup_scripts/compost/compost_values.js; its rows were split into these files unchanged.

Rows come from the dump's "now" table: every item whose chance comes from a values() row (source "value", plus any
such row an exclusion blocks), at that chance and in that values() section. So a dump taken with these files loaded
regenerates them exactly, and a regeneration never changes a chance by itself. Items listed in a hand-written file of
the same tree (any .js there that calls values() and is not generated, e.g. the QoL-4 <mod>/compost.js files) are
skipped: those files own their rows.

To change a chance or add an item by hand: put the row in a hand-written compost.js in the mod's folder and rerun
this (the generated row then goes). Hand-written files load after the generated ones (priority 10), so the hand row
wins even before the rerun.

--add-new also gives a row, at its original chance, to every item the dump's "original" table (the composter table
as vanilla + mods registered it) has that has no row yet: a new mod's own compostables. SKIP_ORIGINAL names the
originals left out on purpose. Ids the item dict has no key for get one, in a generated block of item_dict.js.

  python3 tools/gen_compost_values.py [--dump kubejs/exported/compost/compost.json] [--add-new] [--check | --dry-run]

--check writes nothing and exits 1 when the files on disk differ from what this would write.
"""
import argparse
import json
import re
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from food_catalog import INSTANCE, DICT, parse_dict, best_key, new_key  # noqa: E402
import gen_out  # noqa: E402

ROOT = INSTANCE / 'development/creativeDelight/src/main/resources/kubejs_startup'
# Namespaces whose file goes to Creative Brewing's startup tree instead (creative_brewing.md 4.2 phase 1, 2026-11-01).
CB_ROOT = INSTANCE / 'development/creativeBrewing/src/main/resources/kubejs_startup'
CB_NAMESPACES = {'vinery', 'brewinandchewin'}
ROOTS = (ROOT, CB_ROOT)


def root_of(folder):
    return CB_ROOT if folder in CB_NAMESPACES else ROOT


def rel(path):
    for r in ROOTS:
        if path.is_relative_to(r):
            return str(path.relative_to(r)) + ('' if r == ROOT else ' (CB)')
    return str(path)
OUT_NAME = 'compost_values.js'
DUMP = INSTANCE / 'kubejs/exported/compost/compost.json'
MARK = '// GENERATED by tools/gen_compost_values.py'
PRIORITY = 10
BLOCK_START = '// ############################## Compost items (generated by tools/gen_compost_values.py) ##############################'
BLOCK_END = '// ===== end compost items (generated) ====='

# Namespaces with no `// requires:` line (always present). Pack items (kubejs:, creativeengineering:) go to
# creativeengineering/.
NO_REQUIRES = {'minecraft', 'creativeengineering'}
FOLDER = {'kubejs': 'creativeengineering'}
# Sections in file order after the rule categories the dump lists (values() labels that are not rules).
EXTRA_SECTIONS = ['crates', 'other']

# Comments kept from the hand-edited single file.
NS_NOTES = {
    'alexsmobs': "Its banana is merged into Neapolitan's (item_merges.js).",
    'farmersrespite': "Its coffee is merged into Rustic Delight's (item_merges.js).",
    'brewinandchewin': "The 4.5.0 port's own chances (BrewinAndChewinForge.commonSetup).",
}
ITEM_NOTES = {
    'corn_delight:wild_corn': 'flower-tagged; kept with the crops like the other wild crops',
    'createaddition:chocolate_cake': "Create Crafts & Additions' (Neapolitan's merged into it)",
}
# Originals --add-new leaves out: merged away, or left to the rules / not compostable on purpose.
SKIP_ORIGINAL = {
    'alexsmobs:banana', 'neapolitan:chocolate_cake', 'farmersrespite:coffee_berries',   # merged (item_merges.js)
    'abnormals_delight:yucca_gateau_slice', 'immersive_weathering:upgrade_aquatic/river_bark',
    'oceanic_delight:sponge_cake', 'oceanic_delight:sponge_cake_slice', 'oceanic_delight:wild_sea_grape',
    'miners_delight:baked_cave_carrot', 'miners_delight:cave_carrot', 'miners_delight:crunchy_bar',
    'miners_delight:gossypium', 'miners_delight:nutritional_bar', 'miners_delight:spider_leg',
}


def fmt(x):
    s = ('%.3f' % x).rstrip('0').rstrip('.')
    return s if '.' in s else s + '.0'


def folder_of(item_id):
    ns = item_id.split(':', 1)[0]
    return FOLDER.get(ns, ns)


def is_generated(path):
    try:
        return MARK in '\n'.join(path.read_text().split('\n')[:8])
    except OSError:
        return False


def hand_rows(key_val):
    """Item ids listed in the tree's hand-written values() files -> file (relative to ROOT)."""
    out = {}
    for f in sorted(p for r in ROOTS for p in r.glob('*/*.js')):
        text = f.read_text()
        if is_generated(f) or not re.search(r'\b(C|compost)\.values\(', text):
            continue
        for key in re.findall(r'\[i\.(\w+),', text):
            iid = key_val.get(key)
            if iid:
                out[iid] = rel(f)
            else:
                print(f'warning: {rel(f)}: i.{key} is not in item_dict.js')
    return out


def dict_block(src, new_entries):
    s, e = src.find(BLOCK_START), src.find(BLOCK_END)
    old = []
    if s >= 0 and e >= 0:
        old = [(m.group(1), m.group(2)) for m in re.finditer(r"^i\.(\w+)\s*=\s*'([^']*)'", src[s:e], re.M)]
    rows = sorted(set(old) | set(new_entries), key=lambda kv: (kv[1], kv[0]))
    out = [BLOCK_START,
           "// Compostable items the dict had no key for (Creative Delight's kubejs_startup/<mod>/compost_values.js).",
           '']
    by_ns = OrderedDict()
    for k, v in rows:
        by_ns.setdefault(v.split(':', 1)[0], []).append((k, v))
    for ns, group in by_ns.items():
        out.append(f'// ===== {ns} ({len(group)}) =====')
        w = max(len(k) for k, _ in group)
        out += [f"i.{k.ljust(w)} = '{v}';" for k, v in group]
        out.append('')
    out.append(BLOCK_END)
    block = '\n'.join(out)
    if s >= 0 and e >= 0:
        return src[:s] + block + src[e + len(BLOCK_END):]
    anchor = src.find('// ############################## Validation')
    if anchor < 0:
        raise SystemExit('item_dict.js: no Validation header to insert before')
    return src[:anchor] + block + '\n\n' + src[anchor:]


def render(folder, groups, order):
    """groups: section -> [(item id, dict key, chance)] for one folder. Returns the file text."""
    total = sum(len(v) for v in groups.values())
    namespaces = sorted({r[0].split(':', 1)[0] for rows in groups.values() for r in rows})
    out = [f'// priority: {PRIORITY}']
    out += [f'// requires: {gen_out.requires_mod(ns)}' for ns in namespaces if ns not in NO_REQUIRES]
    out += [
        f'{MARK} from a /dumpcompost dump: do not edit, rerun it. To change a',
        '// chance, put the row in a hand-written compost.js in this folder and rerun (the generator skips items listed',
        '// there; that file loads after this one, so its row wins meanwhile).',
        '// Moved from the pack\'s startup_scripts/compost/compost_values.js 2026-10-25, rows unchanged.',
        f'// Compost values for {folder}: {total} items. Row: [i.<item_dict key>, chance]; chance 0-1 or a tier name from',
        '// creativeengineering/compost_rules.js; 0 = not compostable. A row beats the rules; the exclusions there beat a',
        '// row. Engine: global.compost (patcherMod\'s func/compost.js). Startup script in the CD jar: CD rebuild + restart.'
        if folder not in CB_NAMESPACES else
        '// row. Engine: global.compost (patcherMod\'s func/compost.js). Startup script in the CB jar (moved from CD\'s tree\n'
        '// 2026-11-01; the rules file above is in CD\'s tree): CB rebuild + restart.',
    ]
    for ns in namespaces:
        if ns in NS_NOTES:
            out.append(f'// {ns}: {NS_NOTES[ns]}')
    out += ['', ';(function () {', '\tvar i = global.item', '\tvar C = global.compost']
    for cat in order:
        rows = groups.get(cat)
        if not rows:
            continue
        rows = sorted(rows, key=lambda r: r[0])
        out += ['', f"\tC.values('{cat}', ["]
        w = max(len(k) for _, k, _ in rows) + 3
        for item_id, key, chance in rows:
            line = f"\t\t[{('i.' + key + ',').ljust(w)} {fmt(chance)}],"
            if item_id in ITEM_NOTES:
                line += ' // ' + ITEM_NOTES[item_id]
            out.append(line)
        out.append('\t])')
    out += ['})()', '']
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--dump', default=str(DUMP))
    ap.add_argument('--add-new', action='store_true', help="also add the dump's original items that have no row")
    ap.add_argument('--check', action='store_true', help='write nothing; exit 1 if the files differ')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    d = json.load(open(a.dump))
    src, key_val, by_id = parse_dict()
    taken = set(key_val)
    hand = hand_rows(key_val)

    rows = {}   # item id -> (section, chance)
    for table in (d['now'], d['excluded']):
        for item_id, info in table.items():
            if info.get('source') == 'value' and item_id not in hand:
                rows[item_id] = (info.get('category') or 'other', info['chance'])
    unlisted = sorted(i for i in d['original'] if i not in rows and i not in hand and i not in d['excluded']
                      and i not in SKIP_ORIGINAL)
    if a.add_new:
        for item_id in unlisted:
            info = d['now'].get(item_id) or {}
            rows[item_id] = (info.get('category') or 'other', d['original'][item_id])
    elif unlisted:
        print(f'{len(unlisted)} original compostables with no row (--add-new adds them): ' + ', '.join(unlisted))

    order = [c['name'] for c in d['categories']] + [s for s in EXTRA_SECTIONS if s not in
                                                    [c['name'] for c in d['categories']]]
    order += sorted({s for s, _ in rows.values()} - set(order))
    files = defaultdict(lambda: defaultdict(list))
    new_keys = []
    for item_id, (cat, chance) in rows.items():
        if by_id.get(item_id):
            key = best_key(item_id, by_id[item_id])
        else:
            key = new_key(item_id, taken)
            taken.add(key)
            new_keys.append((key, item_id))
        files[folder_of(item_id)][cat].append((item_id, key, chance))

    wanted = {root_of(f) / f / OUT_NAME: render(f, g, order) for f, g in files.items()}
    stale = [p for r in ROOTS for p in r.glob('*/' + OUT_NAME) if p not in wanted and is_generated(p)]
    changed = [p for p, t in wanted.items() if not p.exists() or p.read_text() != t]

    print(f'{len(rows)} rows in {len(wanted)} files ({len(hand)} items skipped: hand-written), '
          f'{len(changed)} to write, {len(stale)} stale, {len(new_keys)} new item_dict keys')
    for p in sorted(changed):
        print(f'  {"new " if not p.exists() else "diff"} {rel(p)}')
    for p in stale:
        print(f'  stale {rel(p)}')
    if a.check:
        sys.exit(1 if changed or stale or new_keys else 0)
    if a.dry_run:
        return
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p])
    for p in stale:
        p.unlink()
    if new_keys:
        DICT.write_text(dict_block(src, new_keys))
    print(f'wrote {len(changed)} files, removed {len(stale)}' + (f', {len(new_keys)} keys to item_dict.js' if new_keys else ''))


if __name__ == '__main__':
    main()
