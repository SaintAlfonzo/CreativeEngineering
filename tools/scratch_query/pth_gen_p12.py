import os

HERE = os.path.dirname(os.path.abspath(__file__))
L = []
w = L.append


def zomb(x, y, z, tag):
    return (f"> summon minecraft:zombie {x} {y} {z} {{Tags:[\"{tag}\",\"pth\"],PersistenceRequired:1b,IsBaby:0b,"
            f"CanPickUpLoot:0b,Attributes:[{{Name:\"minecraft:generic.movement_speed\",Base:0d}},"
            f"{{Name:\"minecraft:generic.max_health\",Base:100d}}],Health:100f}}")


w("# generated by tools/scratch_query/pth_gen_p12.py (r1115 phase 12, SQ-PTH scratch fixes): edit the generator")
w("pace 1")
w("\n## P12-setup | gamerules, night, forceload, bots (not a test row)")
w("bootexpect Done \\(")
for c in ("gamerule doMobSpawning false", "gamerule doDaylightCycle false", "gamerule doFireTick false",
          "gamerule randomTickSpeed 0", "gamerule doInsomnia false", "gamerule doPatrolSpawning false",
          "gamerule doTraderSpawning false", "time set 18000", "weather clear 1000000",
          "forceload add 992 976 1231 1215"):
    w("> " + c)
w("sleep 8")
w("> pbot spawn P 1000.5 -60 990.5 minecraft:overworld survival")
w("sleep 3")
w("> clear P")
w("> zpth player P")
w("expect \\[zpth\\] player P minecraft:player")
w("reject Unknown or incomplete command")

# ---- SQ-PTH-03b
w("\n## SQ-PTH-03b | 20-block drops (100 hp zombies, base speed 0): plain, lone web ground, lone web 5 up, 3 stacked, cube, ripe berry bush; 5-block drop into a berry bush")
w("> setblock 1004 -60 1090 minecraft:cobweb")
w("> setblock 1008 -55 1090 minecraft:cobweb")
w("> fill 1012 -60 1090 1012 -58 1090 minecraft:cobweb")
w("> fill 1015 -60 1089 1017 -58 1091 minecraft:cobweb")
w("> setblock 1020 -60 1090 minecraft:sweet_berry_bush[age=3]")
w("> setblock 1024 -60 1090 minecraft:sweet_berry_bush[age=3]")
w("> zpth watchnew minecraft:zombie z03 260 1 1012 -50 1090 13.9")
for x, tag, y in ((1000, "z03p", -40), (1004, "z03w", -40), (1008, "z03u", -40), (1012, "z03s", -40),
                  (1016, "z03c", -40), (1020, "z03b", -40), (1024, "z03d", -55)):
    w(zomb(f"{x}.5", y, "1090.5", tag))
w("sleep 9")
for t in ("z03p", "z03w", "z03u", "z03s", "z03c", "z03b", "z03d"):
    w(f"> zpth mod {t}")
w("look damage 100 - hp: plain about 16, lone web about 13.6, 3 webs about 9.8, cube 0 and hangs, bush 16 plus thorns, 5-block bush drop 2; fall distance on entering the lone web 5 up scales (about 14.5 -> 12.4), never about 1")

# ---- SQ-PTH-06b first half
w("\n## SQ-PTH-06b | items and orbs into a lone web and a cube top; held 30 s; one web broken (fall the same tick); the rest kept for the restart")
w("> setblock 1040 -57 1120 minecraft:cobweb")
w("> setblock 1044 -57 1120 minecraft:cobweb")
w("> fill 1047 -59 1119 1049 -57 1121 minecraft:cobweb")
for x, tag in ((1040, "i6a"), (1044, "i6b"), (1048, "i6c")):
    for mx, mz in ((0.02, 0.01), (-0.02, 0.02), (0.01, -0.02)):
        w(f"> summon minecraft:item {x}.5 -54 1120.5 {{Item:{{id:\"minecraft:stone\",Count:1b}},PickupDelay:32767,Motion:[{mx}d,0d,{mz}d],Tags:[\"{tag}\",\"i6\"]}}")
    w(f"> summon minecraft:experience_orb {x}.5 -54 1120.5 {{Value:3,Tags:[\"{tag}\",\"i6\"]}}")
w("sleep 5")
w("> zpth mod i6")
w("sleep 30")
w("> zpth mod i6")
w("> zpth watch i6b 20 1")
w("> setblock 1044 -57 1120 minecraft:air")
w("sleep 2")
w("> zpth mod i6b")
w("> save-all")
w("waitlog Saved the game 60")
w("look i6a and i6c: same positions and ng=true at both reads 30 s apart; i6b: y drops from the first tick after the break, ng=false")

# ---- SQ-PTH-11c
w("\n## SQ-PTH-11c | elevated cube: snowballs from z 994.5 / 995.5 / 996.2, pearl from 995.5; egg dropped onto a lone web; potion, firework, fireball")
w("> fill 1090 -57 1000 1092 -55 1002 minecraft:cobweb")
w("> fill 1091 -58 994 1091 -58 996 minecraft:stone")
w("> zpth watchnew minecraft:snowball s11 600 1 1091.5 -56 999 7")
for z in (994.5, 995.5, 996.2):
    w("> item replace entity P weapon.mainhand with minecraft:snowball")
    w(f"> tp P 1091.5 -57 {z} 0 0")
    w("> zpth use P")
    w("sleep 2")
w("> zpth watchnew minecraft:ender_pearl p11 200 1 1091.5 -56 999 7")
w("> item replace entity P weapon.mainhand with minecraft:ender_pearl")
w("> tp P 1091.5 -57 995.5 0 0")
w("> zpth use P")
w("sleep 4")
w("> zpth player P")
w("> setblock 1100 -60 1000 minecraft:cobweb")
w("> zpth watchnew minecraft:egg e11 100 1 1100.5 -58 1000.5 3")
w("> summon minecraft:egg 1100.5 -58 1000.5 {Motion:[0d,0d,0d]}")
w("sleep 3")
w("> tp P 1091.5 -57 995.5 0 0")
w("> zpth watchnew minecraft:potion q11 400 4 1091.5 -57 999 8")
w("> item replace entity P weapon.mainhand with minecraft:splash_potion{Potion:\"minecraft:slowness\"}")
w("> zpth use P")
w("sleep 4")
w("> zpth watchnew minecraft:firework_rocket f11 200 2 1091.5 -56 999 7")
w("> item replace entity P weapon.mainhand with minecraft:crossbow{Charged:1b,ChargedProjectiles:[{id:\"minecraft:firework_rocket\",Count:1b,tag:{Fireworks:{Flight:1b,Explosions:[{Type:0b,Colors:[I;16711680]}]}}}]}")
w("> zpth use P")
w("sleep 4")
w("> tp P 1086.5 -60 990.5")
w("sleep 18")
w("> summon minecraft:fireball 1091.5 -50 1001.5 {power:[0d,-0.1d,0d],Tags:[\"fb11\"]}")
w("> zpth watch fb11 200 2")
w("sleep 6")
w("look s11: all three gone (995.5 in the edge cell); p11 gone and P in the cube; e11 gone in the web cell; q11 settles and sinks; f11 holds then gone at flight time; fb11 gone inside the cube")

# ---- SQ-PTH-25b
w("\n## SQ-PTH-25b | /cdevbench passthrough twice (Devtools 14:39): 12 cases")
w("> tp P 1150.5 -60 1150.5")
w("> execute as P at P run cdevbench passthrough")
w("waitlog \\[cdevbench\\] passthrough: .* calls per case 300")
w("> execute as P at P run cdevbench passthrough")
w("waitlog \\[cdevbench\\] passthrough: .* calls per case .*\\n?.*")
