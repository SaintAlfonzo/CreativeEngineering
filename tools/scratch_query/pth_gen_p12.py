w("shell python3 -c \"import json;d=json.load(open('kubejs/exported/perf/passthrough_bench.json'));print({k:v for k,v in d.items() if k!='cases'});[print(c['id'],c['median_ns'],c['p99_ns']) for c in d['cases']]\"")
