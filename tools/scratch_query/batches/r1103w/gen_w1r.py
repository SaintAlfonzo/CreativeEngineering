#!/usr/bin/env python3
"""Writes w_1r_B.qb (run r1103w): the w_1_B.qb rows that use the /zq under probe or judge its output, for the W1b
restart. W1 ran them with a broken probe (13:41 IllegalAccess on getAllStarts, 15:2x "kind is not a function"; both
fixed in tools/scratch_query/zq_probe.js). The generation-time [earth-fill] / [meta-structures] lines are spread over
W1's three logs (boot 1 up to the 14:38 OOM, boot 2, the W1b boot), so the judges that read them get ../w1_all.log,
built by row W1R-00; the /zq under judges keep logs/latest.log (the probe lines of this boot).
Run: python3 gen_w1r.py > w_1r_B.qb
"""
import re, sys, os

src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'w_1_B.qb')).read().split('\n')
rows, cur = [], None
for ln in src:
    if ln.startswith('## '):
        cur = [ln]; rows.append(cur)
    elif cur is not None:
        cur.append(ln)
NEED = re.compile(r'zq under|efb_judge|\\\[zq\\\] under|\[zq\] under')
GEN_LOG = re.compile(r"(efb_judge\.py (?:gone wge|log|vslog|on)) logs/latest\.log")
GREP_GEN = re.compile(r"(grep[^|;]*(?:earth-fill|pruned \[0-9\]\* of|dropped \[0-9\]\* of|meta-structures)[^|;]*?) logs/latest\.log")
out = ['# Run r1103w, W1b rerun: w_1_B.qb rows with the /zq under probe (fixed) or its judges. Generated by gen_w1r.py.',
       '# Same RES as w_1_B.qb (captures PL, HI, DE, ... from W1). Generation-time log lines: ../w1_all.log (W1R-00).',
       'pace 2', '',
       '## W1R-00 | setup: W1 logs joined (boot 1 to the OOM, boot 2, this boot) for the earth-fill judges',
       'shell cat $INST/perf/runs/r1103w/w/w1_boot1_full.log $INST/perf/runs/r1103w/w/srvlogs/bootW1.log logs/latest.log > ../w1_all.log; '
       'echo "earth-fill lines: $(grep -c "\\[earth-fill\\]" ../w1_all.log)"', '']
ids = []
for r in rows:
    body = '\n'.join(r)
    if not NEED.search(body):
        continue
    ids.append(r[0].split('|')[0][3:].strip())
    for ln in r:
        ln = GEN_LOG.sub(r'\1 ../w1_all.log', ln)
        ln = GREP_GEN.sub(r'\1 ../w1_all.log', ln)
        if ln.startswith('shell') and re.search(r'earth-fill|meta-structures|undead_castle at chunk', ln) and 'zq\\] under' not in ln:
            ln = ln.replace('logs/latest.log', '../w1_all.log')
        out.append(ln)
print('\n'.join(out))
sys.stderr.write('%d rows: %s\n' % (len(ids), ','.join(ids)))
