#!/bin/bash
# r1106spf (SQ-SPF): composes the boot batches from the parts in this folder. Run from anywhere.
cd "$(dirname "$0")" || exit 1
X=../../qb_extract.py
{ cat b0_fixture.qb;
  printf '\n## SQ-SPF-DUMP-base | /dumpall baseline\n> dumpall\nwaitlog \\[dumpall\\] all \\d+ dumps done 900\n> save-all flush\nsleep 5\n'; } > b0.qb
{ echo "# r1106spf boot 1: same save as b0, 18:5x builds (oldsave_swap.sh). Generated by gen.sh."; cat _b1_new.qb | grep -v '^pace'
  grep -v '^pace\|^# ' _b1_rerun_extra.qb; sed 's/@S@//' _probes.qb | grep -v '^pace\|^# '
  python3 $X '^SQ-(STL|CS-0[128]|MB-0[1-6]|VS|SPC|CDV-0[124]|TD|IP-15)' _rerun_A.qb
  python3 $X '^SQ-CDV-03$' _rerun_A.qb; printf '> save-all flush\nsleep 5\n\n'
  python3 $X '^SQ-CS-06$' _rerun_A.qb; } | sed '1a pace 1' > b1.qb
cp _b2_new.qb b2.qb
cat > b1c.qb <<'Q'
# r1106spf boot 1c: same save, CD toml [campfire] rainDouses = false, useComfort = false (set before the boot).
pace 1
## SQ-CFR-06 | rainDouses = false: open-sky campfire stays lit
> setblock 90 -60 -44 minecraft:campfire[lit=true]
> weather rain
sleep 20
> execute if block 90 -60 -44 minecraft:campfire[lit=true]
expect Test passed
> weather clear

## SQ-CFR-07b | useComfort = false: regeneration near a campfire
> pbot spawn qa 92 -60 -20 minecraft:overworld survival
> setblock 90 -60 -20 minecraft:campfire[lit=true]
> effect clear qa
sleep 3
> data get entity qa ActiveEffects
expect minecraft:regeneration|Id: 10
Q
cat > b1n.qb <<'Q'
# r1106spf boot 1n: same save without creativedevtools-*.jar (SQ-SPF-31).
pace 1
## SQ-SPF-31 | Devtools absent
bootexpect Done \(
bootreject (?i)ERROR.*creativedevtools
bootreject (NoClassDefFoundError|ClassNotFoundException).*(creativedevtools|ceperfbot|BlockStateLookupHook)
> dumpall
> cegen list
count Unknown or incomplete command == 2
> zq tagsof minecraft:stick
shell grep -c "creativedevtools" logs/latest.log; ls mods | grep -ci devtools
look removed items still lose their tags (compare.py: removed item ids carry no tags in this boot is not dumped; check a known removed id with zq tagsof)
Q
cat > jx.qb <<'Q'
# r1106spf SQ-SPF-111: one Creative jar removed (set by the runner), same save.
pace 1
## SQ-SPF-111@J@ | boots without the jar
bootexpect Done \(
bootreject (NoClassDefFoundError|ClassNotFoundException).*(com\.SaintAlfonzo|ce\.shared)
bootreject (Mixin apply failed|InvalidInjectionException).*com\.SaintAlfonzo
kjsreject ReferenceError
shell grep -E "Missing or unsupported mandatory dependencies" -A6 logs/latest.log | head; grep -hE "ReferenceError|Error occurred while handling event" logs/kubejs/*.log | head -5; grep -ciE "\bERROR\b" logs/latest.log
look only missing-content warnings the writeups expect
Q
for j in compat magic equipment worldgen calendar; do sed "s/@J@/-$j/" jx.qb > jx_$j.qb; done
for f in b0 b1 b2 b1c b1n jx_compat; do echo "$f $(python3 ../../qrun.py list $f.qb | wc -l)"; done
