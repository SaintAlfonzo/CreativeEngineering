def errshell(pat, label):
    """shell lines: list ERR lines of latest.log naming pat, then fail when any."""
    return (f"shell grep -nE \"{ERR}\" logs/latest.log | grep -iE \"{pat}\" | cut -c1-300 | head -8; echo \"ERR lines naming {label}: $(grep -E \"{ERR}\" logs/latest.log | grep -ciE \"{pat}\")\"\n"
            f"shell test \"$(grep -E \"{ERR}\" logs/latest.log | grep -ciE \"{pat}\")\" = 0\n")


def lootroll(table, n):
    return f"> zhh2 lootroll {table} {n}\nwaitlog \\[zhh2\\] done 30\nexpect \\[zhh2\\] lootroll {table} rolls {n}, ids [1-9]\n"


def write(name, text):
    with open(os.path.join(OUTDIR, name), 'w') as f:
        f.write(text)
    print('wrote', name)


def a0():
    t = f"""# r1115 phase 7, boot A0: SQ-DEP-09a, full pack (installed mods/ jars). Phase 8 (p8_a0.qb) runs on the same boot.
# Generated by tools/scratch_query/dep_gen_p7.py (edit there).
# Server: NOSWAP=1 prep_srv.sh OUT p7a0 A difficulty=normal (superflat, ground top y -61).
# Before boot: c3_probe.js -> zz_c3_probe.js, hh_mw_probe.js -> zz_hh2.js, zqn_probe.js -> zz_zqn_probe.js.
# "Break it": Block.getDrops with an empty hand (zc3 loot, what a survival break rolls) and a setblock destroy (drops as
# item entities, counted by zc3 items).
pace 1

{SETUP}
## SQ-DEP-09a | full pack: every creativedelight:mods pack enabled; corn maze loot; pancake, jam jar, clover drops; no ERR line
> datapack list enabled
waitlog data packs? enabled 20
"""
    for m in PACK_MODS:
        t += f"expect creativedelight:mods/{m}\\b\n"
    t += lootroll('hearthandharvest:chests/corn_maze', 10)
    t += lootroll('hearthandharvest:chests/corn_maze_center', 10)
    t += f"> loot spawn {X} {Y + 2} {Z} loot hearthandharvest:chests/corn_maze\nexpect Dropped \\d+\n"
    t += f"> setblock {X + 1} {Y} {Z} rusticdelight:pancakes[servings=2]\n> zc3 loot {X + 1} {Y} {Z} none 1\nwaitlog \\[c3\\] done 20\nexpect \\[c3\\] loot .*rusticdelight:pancakes.*supplementaries:pancake x4\n"
    t += f"> setblock {X + 2} {Y} {Z} vintagedelight:fd_lemon_jam_jar[jars=3]\n> zc3 loot {X + 2} {Y} {Z} none 1\nwaitlog \\[c3\\] done 20\nexpect \\[c3\\] loot .*fd_lemon_jam_jar.*fruitsdelight:lemon_jelly x3\n"
    t += f"> setblock {X + 3} {Y} {Z} hearthandharvest:four_leaf_clover\n> zc3 loot {X + 3} {Y} {Z} none 1\nwaitlog \\[c3\\] done 20\nexpect \\[c3\\] loot .*four_leaf_clover.*buzzier_bees:four_leaf_clover x1\n"
    t += f"> kill @e[type=minecraft:item]\nsleep 1\n"
    for dx in (1, 2, 3):
        t += f"> setblock {X + dx} {Y} {Z} minecraft:air destroy\n"
    t += f"sleep 1\n> zc3 items {X + 2} {Y} {Z} 4\nwaitlog \\[c3\\] done 20\n"
    t += errshell("creativedelight|hearthandharvest|vintagedelight|rusticdelight|storagedelight|creativeengineering:sawmill|lingerification", 'the row list')
    t += "look the 20 corn maze rolls hold Corn Delight items, cider or caramel apples; the destroy line (zc3 items) shows 4 pancake (servings=2 = two eaten in Rustic's numbering) and a bowl, 3 lemon_jelly, 1 four_leaf_clover\n"
