def zomb(x, y, z, tag, hp=100, extra=""):
    tags = f"\"{tag}\",\"pth\"" + (f",\"{extra}\"" if extra else "")
    return (f"> summon minecraft:zombie {x} {y} {z} {{Tags:[{tags}],PersistenceRequired:1b,IsBaby:0b,"
            f"CanPickUpLoot:0b,Attributes:[{{Name:\"minecraft:generic.movement_speed\",Base:0d}},"
            f"{{Name:\"minecraft:generic.max_health\",Base:{hp}d}}],Health:{hp}f}}")


def mod_is(tag, val):
    v = "(none|-?0\\.000)" if val is None else val.replace(".", "\\.")
    return f"expect \\[zpth\\] mod {tag} minecraft:zombie mod={v} "


def sec_set(section, key, value):
    """Saves KEY under [SECTION] by rename (copy, edit, mv inside config/): Forge's watcher misses it."""
    return (f"shell cp {CFG} config/zz_edit.tmp && python3 $INST/tools/scratch_query/qrun.py toml config/zz_edit.tmp "
            f"{section} {key} {value} && mv config/zz_edit.tmp {CFG} && grep -n '{key} = ' {CFG} | head -12")


def sed_set(pat, rep):
    return f"shell sed -i 's/{pat}/{rep}/' {CFG} && grep -n '{rep.split(' =')[0].strip()} = ' {CFG}"


