def ps03(tag, chance):
	"""SQ-PS15-03 at one SaltLayerVanishChance. Three layouts of 20 ice each in 1-deep holes, x 300..357 step 3:
    L1 z 330 a 1-layer salt layer ON the ice (row text), L2 z 334 a Salt Block beside it, L3 z 338 a 1-layer salt layer
    beside it (in its own hole, on dirt). Only the ice cell gets random ticks (no salt dissolving tick)."""
	L = [f'## SQ-PS15-03{tag} | SaltLayerVanishChance {chance}: 20 ice under a 1-layer salt layer (L1), beside a Salt Block (L2), beside a 1-layer salt layer (L3)',
		 'pace 0.2',
		 '> fill 298 -61 328 362 -58 340 minecraft:grass_block replace minecraft:water',
		 '> fill 298 -60 328 362 -58 340 minecraft:air',
		 '> fill 298 -61 328 362 -61 340 minecraft:grass_block',
		 '> kill @e[type=minecraft:item]']
	xs = [300 + 3 * i for i in range(20)]
	for x in xs:
		L += [f'> setblock {x} -61 330 minecraft:ice', f'> setblock {x} -60 330 vintagedelight:salt[layers=1]',
			  f'> setblock {x} -61 334 minecraft:ice', f'> setblock {x + 1} -61 334 salt:salt_block',
			  f'> setblock {x} -61 338 minecraft:ice', f'> setblock {x + 1} -61 338 vintagedelight:salt[layers=1]']
	L += ['sleep 1', '> cdevtest count 298 -61 330 362 -61 338 minecraft:ice',
		  '> cdevtest count 298 -61 328 362 -60 340 vintagedelight:salt', '> cdevtest items 330 -60 334 40']
	for z, name in ((330, 'L1'), (334, 'L2'), (338, 'L3')):
		for x in xs:
			L.append(f'> cdevtest randomtick {x} -61 {z} {x} -61 {z} 40 nofluids')
			if name == 'L3':
				L.append(f'> cdevtest state {x + 1} -61 {z}')
		L += ['sleep 3', f'> say ps03 {name} read',
			  f'> cdevtest count 298 -61 {z} 362 -61 {z} minecraft:ice',
			  f'> cdevtest count 298 -61 {z} 362 -61 {z} minecraft:water',
			  f'> cdevtest count 298 -61 {z} 362 -60 {z} vintagedelight:salt',
			  f'> cdevtest count 298 -61 {z} 362 -61 {z} salt:salt_block',
			  f'> cdevtest items 330 -60 {z} 34']
	L += ['sleep 1', 'pace 1',
		  r'count \[cdevtest\] verb=randomtick .*changed=[1-9] == 60',
		  ERR,
		  f'look chance {chance}: per layout ice 0 / water 20; L1 salt layers left and item drops (support loss pops the layer before the listener can roll); L2 salt_block 20 kept; L3 layers left (1.0: 0, 0.0: 20 unless washed) and drops; the L3 state read right after each melt shows the same-tick vanish', '']
	return L


