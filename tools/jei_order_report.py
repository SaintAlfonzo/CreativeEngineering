#!/usr/bin/env python3
"""JEI order catalog: where every item, fluid, effect and multiblock sits in the pack's JEI order, which ones have no
place yet (the tagging to-do list, by mod), which JEI never shows and why, and problems in the definition.

Source data:
  kubejs/exported/jei_order.json   written at each JEI start when CEConfig [jei] orderReport = true
                                   (patcherMod compat/jei/PackOrderReport)

    python3 tools/jei_order_report.py           writes feature_writeup/jei_order_catalog.md
    python3 tools/jei_order_report.py --check   exits 1 when the report lists definition problems

Reference: feature_writeup/jei_ordering.md.
"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

INSTANCE = Path(__file__).resolve().parent.parent
REPORT = INSTANCE / 'kubejs/exported/jei_order.json'
OUT = INSTANCE / 'feature_writeup/jei_order_catalog.md'

CLASSES = [
    ('shown', 'shown in JEI'),
    ('hidden_pack', 'hidden by the pack (KubeJS hides, `packHidden`, JEED `hidden_effects`)'),
    ('hidden_mod', 'hidden by a mod (removed at runtime by its JEI plugin)'),
    ('hidden_player', "hidden in JEI's edit mode (config/jei/blacklist.cfg)"),
    ('not_shown', 'never in JEI (no creative tab, no plugin added it)'),
]
PROBLEMS = [
    ('conflicts', 'Placed on two branches (kept the first in definition order)'),
    ('undefinedPaths', 'Tag paths the definition lacks (members sort after their defined siblings, A-Z)'),
    ('emptyNodes', 'Defined nodes with no members'),
    ('missingListEntries', 'List entries that match no known id'),
    ('hiddenButPlaced', 'Placed but not shown (a hidden id in a list or jei tag)'),
]


def md(s):
    return str(s).replace('|', '\\|')


def main():
    check = '--check' in sys.argv
    if not REPORT.exists():
        # Opt-in report: no input is a skip (exit 2, a warnExit code in generators.json), not a failure.
        print(f'skipped: {REPORT.relative_to(INSTANCE)} not found; set [jei] orderReport = true in '
              f'config/creativecommon-common.toml and join a world to write it')
        sys.exit(2)
    data = json.loads(REPORT.read_text(encoding='utf-8'))
    entries = data['entries']
    problems = data.get('problems', {})
    types = list(dict.fromkeys(data.get('types', []) + [e['type'] for e in entries]))

    lines = [
        '# JEI order catalog',
        '',
        'Generated by `python3 tools/jei_order_report.py` from `kubejs/exported/jei_order.json` '
        f"(JEI start {data.get('generated', '?')}, packOrder {data.get('packOrder')}, "
        f"definition loaded {data.get('definitionLoaded')}). Reference: [jei_ordering.md](jei_ordering.md).",
        '',
        '## 0. Summary',
        '',
        '| Type | ' + ' | '.join(c for c, _ in CLASSES) + ' | placed | unplaced (shown) |',
        '|---|' + '---|' * (len(CLASSES) + 2),
    ]
    for t in types:
        rows = [e for e in entries if e['type'] == t]
        cls = Counter(e['class'] for e in rows)
        placed = sum(1 for e in rows if e['class'] == 'shown' and 'path' in e)
        unplaced = sum(1 for e in rows if e['class'] == 'shown' and 'path' not in e)
        lines.append(f'| {t} | ' + ' | '.join(str(cls.get(c, 0)) for c, _ in CLASSES) + f' | {placed} | {unplaced} |')
    lines += ['', 'Classes: ' + '; '.join(f'`{c}` {d}' for c, d in CLASSES) + '.', '']

    # 1. placed, in JEI order
    lines += ['## 1. Placed, in JEI order', '']
    for t in types:
        placed = sorted((e for e in entries if e['type'] == t and 'path' in e and e['class'] == 'shown'),
                        key=lambda e: e.get('position', 1 << 62))
        if not placed:
            continue
        lines += [f'### {t}', '', '| Path | Id | Name | Mod | By |', '|---|---|---|---|---|']
        for e in placed:
            path = e['path'] + (' (undefined)' if e.get('undefinedPath') else '')
            lines.append(f"| {md(path)} | `{e['id']}` | {md(e.get('name', ''))} | {e['mod']} | {e.get('placedBy', '')} |")
        lines.append('')

    # 2. problems
    lines += ['## 2. Definition problems', '']
    total_problems = 0
    for key, title in PROBLEMS:
        items = problems.get(key, [])
        total_problems += len(items)
        lines.append(f'### {title} ({len(items)})')
        lines.append('')
        if not items:
            lines += ['None.', '']
            continue
        for it in items:
            if isinstance(it, dict):
                lines.append('- ' + ', '.join(f'{k}: `{v}`' for k, v in it.items()))
            else:
                lines.append(f'- `{it}`')
        lines.append('')

    # 3. unplaced by mod (the to-do list)
    lines += ['## 3. Shown but not placed, by mod (the tagging to-do list)', '']
    for t in types:
        by_mod = defaultdict(list)
        for e in entries:
            if e['type'] == t and e['class'] == 'shown' and 'path' not in e:
                by_mod[e['mod']].append(e)
        if not by_mod:
            continue
        lines += [f'### {t} ({sum(len(v) for v in by_mod.values())})', '', '| Mod | Count | Ids |', '|---|---|---|']
        for mod, rows in sorted(by_mod.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            ids = ', '.join(f"`{e['id'].split(':', 1)[1]}`" for e in sorted(rows, key=lambda e: e.get('position', 0)))
            lines.append(f'| {mod} | {len(rows)} | {ids} |')
        lines.append('')

    # 4. not shown / hidden
    lines += ['## 4. Not shown in JEI', '']
    for cls, title in CLASSES[1:]:
        rows = [e for e in entries if e['class'] == cls]
        lines += [f'### {title} ({len(rows)})', '']
        if not rows:
            lines += ['None.', '']
            continue
        lines += ['| Type | Id | Mod | Removed by |', '|---|---|---|---|']
        for e in sorted(rows, key=lambda e: (e['type'], e['id'])):
            lines.append(f"| {e['type']} | `{e['id']}` | {e['mod']} | {', '.join(e.get('removedBy', []))} |")
        lines.append('')

    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {OUT.relative_to(INSTANCE)}: {len(entries)} ids, {total_problems} problems')
    if check and total_problems:
        sys.exit(1)


if __name__ == '__main__':
    main()
