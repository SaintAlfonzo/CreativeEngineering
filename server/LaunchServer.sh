#!/bin/bash

# When setting the memory below make sure to include the amount of ram letter. M = MB, G = GB. Don't use 1GB for example, it's 1G
MEMORY="6G"

# The path to the Java to use. Wrap in double quotes ("/opt/jre-17/bin/java"). Use "java" to point to system default install.
JAVAPATH="java"

# Any additional arguments to pass to Java such as Metaspace, GC or anything else
JVMARGS="-XX:FlightRecorderOptions=stackdepth=256,repository=perf/jfr-repo -XX:StartFlightRecording=name=ce,settings=perf/ce-server.jfc,disk=true,maxage=30m,maxsize=512m,dumponexit=true,filename=perf/exit"
# ^ always-on performance recording (Java Flight Recorder): keeps the last 30 minutes (at most 512 MB) in
#   perf/jfr-repo/. Save it with perf/dump.sh when the server lags, or gather everything with perf/report.sh;
#   see perf/README.md. Remove the two -XX options to turn it off. stackdepth=256: the default 64 cuts deep
#   modded stacks. dumponexit: every stop, watchdog crashes included, writes the last 30 minutes to perf/exit/
#   (the newest 3 are kept).

# Don't edit past this point

cd "$(dirname "$0")"

# perf/exit must exist, or JFR writes a file named "exit"; keep its newest 3 recordings
mkdir -p perf/exit
ls -t perf/exit/*.jfr 2>/dev/null | tail -n +4 | xargs -r rm -f --

LAUNCHARGS="$@"
# Launcher can specify path to java using a custom token
if [ "$1" = "ATLcustomjava" ]; then
    LAUNCHARGS="${@:2}"

    echo "Using launcher provided Java from $2"
    JAVAPATH="$2"
fi

echo
echo "Printing Java info below, if the Java version doesn't show below, your Java path is incorrect"
echo -----------------------
echo Java path is $JAVAPATH
$JAVAPATH -version
echo

FINALJAVAARGS="-Xmx$MEMORY $JVMARGS  "
FINALJAVAARGS=$(echo $FINALJAVAARGS | xargs echo -n)

if [ -f "server.jar" ]; then
    echo Using NeoForge ServerStarterJar, resetting user_jvm_args.txt contents
    echo

    echo "# DO NOT EDIT THIS FILE, IT IS AUTO GENERATED BY LaunchServer.bat/sh" >user_jvm_args.txt
    echo "# TO MAKE CHANGES TO RAM OR JVM ARGUMENTS, EDIT LaunchServer.bat/sh" >>user_jvm_args.txt
    echo $FINALJAVAARGS >>user_jvm_args.txt

    # Keep FINALJAVAARGS on the command line: the starter jar runs the server in this same JVM and drops
    # -X options from the args files, so user_jvm_args.txt alone applies neither -Xmx nor -XX.
    # (The pack line here was "$FINALJAVAARGS=", which only printed "command not found".)
fi

echo Launching below command
echo -----------------------
echo $JAVAPATH $FINALJAVAARGS -jar server.jar "$LAUNCHARGS"
echo
$JAVAPATH $FINALJAVAARGS -jar server.jar "$LAUNCHARGS"
read -n1 -r -p "Press any key to close..."
