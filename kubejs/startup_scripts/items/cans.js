// Generated cans (tools/gen_can_types.py -> generation_scripts/food/can_types.json)
function ceCanTypes() {
    var path = 'kubejs/generation_scripts/food/can_types.json'
    try { return JSON.parse(String(JsonIO.readString(path))).cans } catch (err) {
        console.error('[cans] could not read ' + path + ': ' + err)
        return {}
    }
}

function ceCanFood(f, c) {
    f.hunger(c.hunger).saturation(c.modifier)
    if (c.meat) f.meat()
    if (c.fast) f.fastToEat()
    if (c.always) f.alwaysEdible()
    c.effects.forEach(fx => f.effect(fx.effect, fx.ticks, fx.amp, fx.chance))
    if (c.clear_effects) f.eaten(ev => ev.entity.removeAllEffects())   // Canned Powdered Milk
}

StartupEvents.registry('item', e => {
    var i = global.item
    var cans = ceCanTypes()
    var made = 0
    Object.keys(cans).forEach(key => {
        var c = cans[key]
        if (c.existing) return
        var id = i[key]
        if (typeof id !== 'string') { console.warn('[cans] ' + key + ' has no item_dict key, run tools/gen_can_types.py'); return }
        try {
            var b = e.create(id).displayName(c.name).food(f => ceCanFood(f, c))
            if (c.texture) b.texture(c.texture)   // null: own sprite at creativeengineering:item/<id>
            if (c.glow) b.glow(true)
            made++
        } catch (err) {
            console.warn('[cans] could not register ' + id + ': ' + err)
        }
    })
    console.log('[cans] registered ' + made + ' generated cans')
})

// Canned Goods cans that get a recipe here: same food values as the generated cans (their own are 1 to 42 modifiers).
ItemEvents.modification(e => {
    var i = global.item
    var cans = ceCanTypes()
    Object.keys(cans).forEach(key => {
        var c = cans[key]
        if (!c.existing) return
        var id = i[key]
        if (typeof id !== 'string') { console.warn('[cans] ' + key + ' has no item_dict key'); return }
        try {
            e.modify(id, item => item.setFoodProperties(f => ceCanFood(f, c)))
        } catch (err) {
            console.warn('[cans] could not set food on ' + id + ': ' + err)
        }
    })
})
