    e.create('creativeengineering:canned_onion').displayName('Canned Onion').food(veggie)
    e.create('creativeengineering:canned_potato').displayName('Canned Potato').food(veggie)
    e.create('creativeengineering:canned_tomato').displayName('Canned Tomato').food(veggie)
    e.create('creativeengineering:canned_bell_pepper').displayName('Canned Bell Pepper').food(veggie)
    e.create('creativeengineering:canned_cactus_flesh').displayName('Canned Cactus Flesh').texture(veggieCan).food(veggie)
    e.create('creativeengineering:canned_gongylidia').displayName('Canned Gongylidia').food(veggie)

