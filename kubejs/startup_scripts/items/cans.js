// Food cans made in server_scripts/cooking/canning.js (ingredient + empty can, or fewer ingredients + an additive).
// Cans without .texture() use their own sprite (kubejs/assets/creativeengineering/textures/item/<id>.png, drawn in
// textureswapper/canned/newcan); the rest borrow their group's: carrot (raw veggie), apple (raw fruit), raw beef
// (raw meat), raw salmon (raw fish). Generated cans get theirs from can_types.json "texture" (null = own sprite);
// sections without a group sprite still use Canned Goods' beetroot can. Some Canned Goods sprites are replaced under
// kubejs/assets/canned_goods/.
//
// Food values are one serving (one meal). The number of servings per can lives in
// generation_scripts/food/can_servings.json (patcherMod food.CanServings), not here:
//   raw veggie  2 servings of a Baked Potato meal (5 hunger, 6 sat = 0.6 modifier)
//   raw fruit   3 servings of a Fruit Meal        (5 hunger, 3 sat = 0.3 modifier)
//   raw meat    4 servings of a Meat Meal         (5 hunger, 3 sat = 0.3 modifier), meat() so wolves eat them
// KubeJS saturation() is the modifier: saturation points = hunger x modifier x 2.
// Dict keys: startup_scripts/_lib/item_dict.js "canning" section. Food types: generation_scripts/food/food_types.json.
//
// The cans below are hand-written (raw veggie/fruit/meat). Not canned: mint, acorn, grapes, mite crust, Alex's Mobs
// bananas, and raw or cooked ham, chevon, hoglin, kangaroo, moose, bison, bunfungus. Coverage: feature_writeup/can_parity.md.
// Every other can (more raw fruit, shulker, raw fish, hazard, special, cookies, cooked, bread, salad, soup, meal, pie,
// feast, drink, golden) is generated by tools/gen_can_types.py into generation_scripts/food/can_types.json and registered by the second block
// at the bottom of this file: one meal = the food it holds x a multiplier, effects copied with scaled durations.
// Generated cans marked "existing" are Canned Goods items (canned_bread, canned_beef...): only their food values change.

