// Placeable food tags, drawn as tooltip lines by client_scripts/placeable_tooltip.js:
//   #creativeengineering:placeable                 can be put down as a block ("Placeable")
//   #creativeengineering:placeable/sneak           ...only while sneaking (also in #placeable)
//   #creativeengineering:placeable_on_plate        Display Delight Food Plate ("Placeable on plate")
//   #creativeengineering:placeable_on_small_plate  Display Delight Small Food Plate ("Placeable on small plate")
//   #creativeengineering:placeable_on_coaster      Brewin' and Chewin' coaster ("Placeable on a coaster", alcohol.md 8.3)
//
// #creativeengineering:placeable_on_coaster also goes into #brewinandchewin:placeable_on_coaster, the tag the coaster
// checks ([coaster] taggedItemsOnly): the port fills it with its own modelled items, this adds the Display Delight
// foods that tools/gen_coaster_models.py gives a coaster model (alcohol.md 12).
//
// The lists live in kubejs/generation_scripts/food/placeable.json (tag -> item_dict keys), generated by
// python3 tools/placeable_catalog.py from /dumpplaceable. Change the rules in the tool, not the json.
// Reference: feature_writeup/placeable_food.md, catalog feature_writeup/placeable_catalog.md

ServerEvents.tags('item', e => {
	var t = global.tags
	var i = global.item
	var path = 'kubejs/generation_scripts/food/placeable.json'
	var data = null
	try { data = JSON.parse(String(JsonIO.readString(path))) } catch (err) {
		console.error('[placeable] could not read ' + path + ': ' + err)
		return
	}

	var tagKeys = {
		'placeable': 't_placeable',
		'placeable/sneak': 't_placeable_sneak',
		'placeable_on_plate': 't_placeable_on_plate',
		'placeable_on_small_plate': 't_placeable_on_small_plate',
		'placeable_on_coaster': 't_placeable_on_coaster',
	}
	var missing = []
	var counts = []
	Object.keys(tagKeys).forEach(name => {
		var tag = i[tagKeys[name]]
		if (!tag) {
			console.warn(`[placeable] no item_dict key i.${tagKeys[name]} - run python3 tools/placeable_catalog.py, then restart`)
			tag = '#creativeengineering:' + name
		}
		var ids = []
		;(data[name] || []).forEach(key => {
			var id = i[key]
			if (typeof id === 'string' && id.charAt(0) !== '#') ids.push(id)
			else missing.push(key)
		})
		t.addTag(e, tag, ids)
		counts.push(name + '=' + ids.length)
	})

	t.addTag(e, i.t_bnc_placeable_on_coaster, i.t_placeable_on_coaster || '#creativeengineering:placeable_on_coaster')

	if (missing.length) {
		console.warn(`[placeable] ${missing.length} key(s) are not item ids in item_dict (new keys need a restart): `
			+ missing.slice(0, 25).join(', ') + (missing.length > 25 ? ' ...' : ''))
	}
	console.log('[placeable] ' + counts.join(', '))
})
