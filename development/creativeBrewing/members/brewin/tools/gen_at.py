#!/usr/bin/env python3
"""Generate src/main/resources/META-INF/accesstransformer.cfg (SRG names, what Forge 1.19.2 reads at runtime)
from tools/accesstransformer.official.cfg (Mojang names, readable and diffable against upstream's AT).

    tools/gen_at.py            (run from development/creativeBrewing/members/brewin; needs build/createMcpToSrg/output.tsrg,
                                which any ./gradlew build creates)

Official AT line forms:
    public net.minecraft.client.Camera eyeHeight                         field
    public net.minecraft.client.Minecraft handleKeybinds()V              method (descriptor in official names)
    public net.minecraft.client.renderer.RenderType$CompositeState       class
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TSRG = os.path.join(ROOT, 'build', 'createMcpToSrg', 'output.tsrg')
SRC = os.path.join(HERE, 'accesstransformer.official.cfg')
OUT = os.path.join(ROOT, 'src', 'main', 'resources', 'META-INF', 'accesstransformer.cfg')


def load_tsrg(path):
    classes = {}
    current = None
    with open(path) as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('tsrg2'):
                continue
            if not line.startswith('\t'):
                left, _right = line.split(' ')[:2]
                current = classes.setdefault(left, {'fields': {}, 'methods': {}})
            elif not line.startswith('\t\t'):
                parts = line.strip().split(' ')
                if len(parts) == 2:
                    current['fields'][parts[0]] = parts[1]
                elif len(parts) == 3:
                    current['methods'][(parts[0], parts[1])] = parts[2]
    return classes


def main():
    classes = load_tsrg(TSRG)
    out = ['# GENERATED by tools/gen_at.py from tools/accesstransformer.official.cfg (SRG names). Do not edit.']
    errors = 0
    for raw in open(SRC):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        m = re.match(r'(\S+)\s+([\w.$]+)(?:\s+(\w+|<init>)(\(.*)?)?$', line)
        if not m:
            print(f'bad line: {raw.rstrip()}', file=sys.stderr)
            errors += 1
            continue
        access, cls, member, desc = m.groups()
        internal = cls.replace('.', '/')
        info = classes.get(internal)
        if info is None:
            print(f'unknown class: {cls}', file=sys.stderr)
            errors += 1
            continue
        if member is None:
            out.append(f'{access} {cls}')
        elif desc is None:
            srg = info['fields'].get(member)
            if srg is None:
                print(f'unknown field: {cls} {member}', file=sys.stderr)
                errors += 1
                continue
            out.append(f'{access} {cls} {srg} # {member}')
        else:
            srg = member if member == '<init>' else info['methods'].get((member, desc))
            if srg is None:
                print(f'unknown method: {cls} {member}{desc}', file=sys.stderr)
                errors += 1
                continue
            out.append(f'{access} {cls} {srg}{desc} # {member}')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print(f'wrote {len(out) - 1} entries to {os.path.relpath(OUT, ROOT)}' + (f', {errors} errors' if errors else ''))
    sys.exit(1 if errors else 0)


if __name__ == '__main__':
    main()
