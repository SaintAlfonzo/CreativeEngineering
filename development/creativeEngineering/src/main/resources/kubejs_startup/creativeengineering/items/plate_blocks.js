// Creative Engineering; moved from kubejs/startup_scripts/items/plate_blocks.js on 2026-11-04 (creative_split.md 7.13, wave 8), rows unchanged.
// Plate storage blocks (creativeengineering:<metal>_plate_block) - fully migrated from Java
// (patcherMod CreativeEngineeringItems used to register these as plain solid Blocks) into
// KubeJS. Same stats as the old Java blocks (Material.METAL, strength 5.0/5.0, metal sound,
// requires a tool). Note: the copper plate block is create_compressed:copper_sheet_block,
// not part of this creativeengineering family.
//
// Blockstate, block model and block-item model are generated by KubeJS from the .textureAll() call
// below (cube_all, textures at creativeengineering:block/plate_block/<metal>_plate_block.png). KubeJS's
// generated pack outranks mod jars, so hand-authored JSONs in this jar would be ignored;
// do not add them back (2026-11-07: they rendered untextured after the jar move).
// Loot table (drop self) is KubeJS's block-builder default, same as the old Java family.
//
// No mineable/tool tag here - CD server creativeengineering/harvest.js owns ALL tool-type (pickaxe)
// and tool-tier tags for every plate block in one place, so tags don't fight between two files.

const PLATE_BLOCK_METALS = [
    'aluminum', 'cast_iron', 'constantan', 'electrum', 'lead',
    'netherite', 'nickel', 'silver', 'steel', 'uranium', 'zinc',
];

StartupEvents.registry('block', e => {
    PLATE_BLOCK_METALS.forEach(metal => {
        e.create('creativeengineering:' + metal + '_plate_block')
            .material('metal')
            .soundType('metal')
            .hardness(5.0)
            .resistance(5.0)
            .requiresTool(true)
            .textureAll('creativeengineering:block/plate_block/' + metal + '_plate_block');
    });
});
