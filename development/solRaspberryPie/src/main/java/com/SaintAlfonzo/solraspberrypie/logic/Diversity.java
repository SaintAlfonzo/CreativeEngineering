package com.SaintAlfonzo.solraspberrypie.logic;

import com.SaintAlfonzo.solraspberrypie.SolRaspberryPie;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraftforge.registries.ForgeRegistries;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * The pack's diversity table (plan_food_diversity_1121.md R1): per-food values that replace Apple Pie's formula and
 * config list, and families whose members share one diet entry. Generated by tools/food_diversity.py into
 * {@code /solraspberrypie/diversity.json} in this jar and read once on first use, on both sides, so tooltips and the
 * server agree without a sync. A food missing from the table keeps Apple Pie's own value.
 */
public final class Diversity {
	private static final Logger LOG = LoggerFactory.getLogger("solraspberrypie/diversity");
	private static final String PATH = "/" + SolRaspberryPie.MOD_ID + "/diversity.json";

	private static Map<ResourceLocation, Double> values;
	private static Map<ResourceLocation, ResourceLocation> canonical;
	/** Resolved family heads per member item, filled lazily (registry lookups after load). */
	private static final Map<Item, Item> HEADS = new HashMap<>();

	/** The table's value for this item, or null when the table does not list it. */
	public static Double value(Item item) {
		load();
		ResourceLocation id = item == null ? null : ForgeRegistries.ITEMS.getKey(item);
		return id == null ? null : values.get(id);
	}

	/** The item whose diet entry this item counts as: its family head, or the item itself. */
	public static Item head(Item item) {
		if (item == null) return null;
		load();
		if (canonical.isEmpty()) return item;
		synchronized (HEADS) {
			Item cached = HEADS.get(item);
			if (cached != null) return cached;
			Item out = item;
			ResourceLocation id = ForgeRegistries.ITEMS.getKey(item);
			ResourceLocation head = id == null ? null : canonical.get(id);
			if (head != null) {
				Item h = ForgeRegistries.ITEMS.getValue(head);
				if (h != null) out = h;
			}
			HEADS.put(item, out);
			return out;
		}
	}

	private static synchronized void load() {
		if (values != null) return;
		Map<ResourceLocation, Double> v = new HashMap<>();
		Map<ResourceLocation, ResourceLocation> c = new HashMap<>();
		try (InputStream in = Diversity.class.getResourceAsStream(PATH)) {
			if (in == null) {
				LOG.warn("No {} in the jar; Apple Pie's values apply", PATH);
			} else {
				JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
				if (root.has("values")) {
					for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("values").entrySet()) {
						ResourceLocation id = ResourceLocation.tryParse(e.getKey());
						if (id != null) v.put(id, e.getValue().getAsDouble());
					}
				}
				if (root.has("families")) {
					for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("families").entrySet()) {
						JsonArray members = e.getValue().getAsJsonArray();
						if (members.size() < 2) continue;
						ResourceLocation head = ResourceLocation.tryParse(members.get(0).getAsString());
						if (head == null) continue;
						for (JsonElement m : members) {
							ResourceLocation id = ResourceLocation.tryParse(m.getAsString());
							if (id != null && !id.equals(head)) c.put(id, head);
						}
					}
				}
				LOG.info("Diversity table: {} values, {} family members", v.size(), c.size());
			}
		} catch (Exception ex) {
			LOG.error("Could not read {}; Apple Pie's values apply", PATH, ex);
			v.clear();
			c.clear();
		}
		canonical = c;
		values = v;
	}

	private Diversity() {}
}
