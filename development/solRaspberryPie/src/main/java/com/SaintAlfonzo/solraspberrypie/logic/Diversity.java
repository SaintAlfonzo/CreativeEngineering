package com.SaintAlfonzo.solraspberrypie.logic;

import com.SaintAlfonzo.solraspberrypie.SolRaspberryPie;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraftforge.registries.ForgeRegistries;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import net.minecraftforge.fml.ModList;
import net.minecraftforge.forgespi.language.IModFileInfo;

import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Predicate;
import java.util.stream.Stream;

/**
 * Diversity tables (plan_food_diversity_1121.md R1, plan_rp_standalone.md P3): per-food values that replace Apple Pie's
 * formula and config list, and families whose members share one diet entry. Raspberry Pie ships none: it reads every
 * {@code solraspberrypie/diversity/*.json} in any loaded mod's jar (the pack's table is Creative Delight's
 * {@code creativedelight.json}, generated by tools/food_diversity.py), merged in mod-id then file-name order, a later file
 * winning an id both list (one line per file pair). Read once on first use by the server (dedicated or integrated); a
 * client on a remote server never reads its own jars: the server's table arrives by {@code S2CDiversity} at login and
 * on /reload (publish_readiness.md PR-RP-17), and until then nothing is overridden. An id whose mod is not loaded is skipped (one INFO count, A6). With no table at all nothing is
 * overridden and Apple Pie's values stand (A7); a food missing from the tables keeps Apple Pie's own value.
 */
public final class Diversity {
	private static final Logger LOG = LoggerFactory.getLogger("solraspberrypie/diversity");
	/** Folder inside a mod jar: {@code solraspberrypie/diversity/<name>.json}. */
	private static final String[] DIR = {SolRaspberryPie.MOD_ID, "diversity"};

	private static Map<ResourceLocation, Double> values;
	private static Map<ResourceLocation, ResourceLocation> canonical;
	/** Resolved family heads per member item, filled lazily (registry lookups after load). */
	private static final Map<Item, Item> HEADS = new HashMap<>();

	/** One table file: where it came from (for the log) and its parsed JSON. */
	public record Source(String name, JsonObject json) {}

	/** The table's value for this item, or null when the table does not list it. */
	public static Double value(Item item) {
		if (!load()) return null;
		ResourceLocation id = item == null ? null : ForgeRegistries.ITEMS.getKey(item);
		return id == null ? null : values.get(id);
	}

	/** The item whose diet entry this item counts as: its family head, or the item itself. */
	public static Item head(Item item) {
		if (item == null) return null;
		if (!load() || canonical.isEmpty()) return item;
		synchronized (HEADS) {
			Item cached = HEADS.get(item);
			if (cached != null) return cached;
			Item out = item;
			ResourceLocation id = ForgeRegistries.ITEMS.getKey(item);
			ResourceLocation head = id == null ? null : canonical.get(id);
			if (head != null) {
				Item h = ForgeRegistries.ITEMS.getValue(head);
				if (h != null) out = h;
			}
			HEADS.put(item, out);
			return out;
		}
	}

	/**
	 * True when a table is current. A physical client with no integrated server running waits for the server's table
	 * (false, nothing read); every server reads the jars once.
	 */
	private static synchronized boolean load() {
		if (values != null) return true;
		if (net.minecraftforge.fml.loading.FMLEnvironment.dist.isClient()
				&& net.minecraftforge.server.ServerLifecycleHooks.getCurrentServer() == null) return false;
		List<Source> sources = new ArrayList<>();
		try {
			sources = findTables();
		} catch (Exception ex) {
			LOG.error("Could not list the diversity tables; Apple Pie's values apply", ex);
		}
		use(sources, ForgeRegistries.ITEMS::containsKey);
		return true;
	}

	/** The current table for {@code S2CDiversity}: {values, family member -> head}; empty maps when there is none. */
	public static synchronized List<Map<ResourceLocation, ?>> snapshot() {
		load();
		return List.of(values == null ? Map.of() : new HashMap<>(values), canonical == null ? Map.of() : new HashMap<>(canonical));
	}

	/**
	 * The server's table on a client (S2CDiversity). Ids this client does not know are dropped (one INFO count); the
	 * family heads are resolved again on first use.
	 */
	public static synchronized void applyRemote(Map<ResourceLocation, Double> v, Map<ResourceLocation, ResourceLocation> c) {
		Map<ResourceLocation, Double> nv = new HashMap<>();
		Map<ResourceLocation, ResourceLocation> nc = new HashMap<>();
		int[] unknown = {0};
		v.forEach((id, val) -> {
			if (ForgeRegistries.ITEMS.containsKey(id)) nv.put(id, val);
			else unknown[0]++;
		});
		c.forEach((id, head) -> {
			if (ForgeRegistries.ITEMS.containsKey(id) && ForgeRegistries.ITEMS.containsKey(head)) nc.put(id, head);
			else unknown[0]++;
		});
		synchronized (HEADS) {
			HEADS.clear();
		}
		canonical = nc;
		values = nv;
		LOG.info("Diversity table from the server: {} values, {} family members; {} ids unknown to this client", nv.size(), nc.size(), unknown[0]);
	}

	/** Leaving a world: the next server's table (or the integrated server's jars) replaces this one. */
	public static synchronized void forget() {
		synchronized (HEADS) {
			HEADS.clear();
		}
		values = null;
		canonical = null;
	}

	/** Every {@code solraspberrypie/diversity/*.json} in the loaded mod files, in mod-id then file-name order. */
	private static List<Source> findTables() throws IOException {
		List<Source> out = new ArrayList<>();
		ModList mods = ModList.get();
		if (mods == null) return out;
		List<IModFileInfo> files = new ArrayList<>(mods.getModFiles());
		files.sort(Comparator.comparing(f -> f.getMods().isEmpty() ? f.getFile().getFileName() : f.getMods().get(0).getModId()));
		for (IModFileInfo info : files) {
			Path dir = info.getFile().findResource(DIR);
			if (!Files.isDirectory(dir)) continue;
			String owner = info.getMods().isEmpty() ? info.getFile().getFileName() : info.getMods().get(0).getModId();
			List<Path> jsons;
			try (Stream<Path> list = Files.list(dir)) {
				jsons = list.filter(p -> p.getFileName().toString().endsWith(".json")).sorted(Comparator.comparing(p -> p.getFileName().toString())).toList();
			}
			for (Path p : jsons) {
				String name = owner + ":" + p.getFileName();
				try (Reader r = Files.newBufferedReader(p, StandardCharsets.UTF_8)) {
					out.add(new Source(name, JsonParser.parseReader(r).getAsJsonObject()));
				} catch (Exception ex) {
					LOG.error("Diversity table {} is unreadable; skipped", name, ex);
				}
			}
		}
		return out;
	}

	/**
	 * Merges the tables (later source wins an id both list, one line per pair), drops ids {@code known} rejects (one INFO
	 * count) and makes the result current. Each source is read on its own: a file of the wrong shape is skipped whole
	 * with one error line, a value that is not a finite number of 0 or more is skipped (one warning count), and the
	 * table is always assigned, so a bad file from any mod never leaves the lookups failing (publish_readiness.md
	 * PR-RP-04). Public for the headless test (tools/test_rp_ladder.sh).
	 */
	public static synchronized void use(List<Source> sources, Predicate<ResourceLocation> known) {
		Map<ResourceLocation, Double> v = new HashMap<>();
		Map<ResourceLocation, String> valueFrom = new HashMap<>();
		Map<ResourceLocation, ResourceLocation> c = new HashMap<>();
		Map<ResourceLocation, String> familyFrom = new HashMap<>();
		Map<String, Integer> overrides = new LinkedHashMap<>();
		List<String> used = new ArrayList<>();
		int[] absent = {0};
		int[] badValues = {0};
		try {
			for (Source src : sources) {
				Map<ResourceLocation, Double> sv = new LinkedHashMap<>();
				Map<ResourceLocation, ResourceLocation> sc = new LinkedHashMap<>();
				int[] sAbsent = {0};
				int[] sBad = {0};
				try {
					read(src, known, sv, sc, sAbsent, sBad);
				} catch (Exception ex) {
					LOG.error("Diversity table {} has the wrong shape ({}); skipped", src.name(), ex.toString());
					continue;
				}
				used.add(src.name());
				absent[0] += sAbsent[0];
				badValues[0] += sBad[0];
				sv.forEach((id, val) -> {
					String before = valueFrom.put(id, src.name());
					if (before != null && !before.equals(src.name())) overrides.merge(src.name() + " over " + before, 1, Integer::sum);
					v.put(id, val);
				});
				sc.forEach((id, head) -> {
					String before = familyFrom.put(id, src.name());
					if (before != null && !before.equals(src.name())) overrides.merge(src.name() + " over " + before, 1, Integer::sum);
					c.put(id, head);
				});
			}
			overrides.forEach((pair, n) -> LOG.info("Diversity table: {} entries of {}", n, pair));
			if (badValues[0] > 0) LOG.warn("Diversity table: {} values skipped (not a finite number of 0 or more)", badValues[0]);
			if (used.isEmpty()) {
				LOG.info("No usable diversity table (solraspberrypie/diversity/*.json) in any mod; Apple Pie's values apply");
			} else {
				LOG.info("Diversity table: {} values, {} family members from {} file(s) ({}); {} ids skipped (mod not loaded)",
						v.size(), c.size(), used.size(), String.join(", ", used), absent[0]);
			}
		} finally {
			synchronized (HEADS) {
				HEADS.clear();
			}
			canonical = c;
			values = v;
		}
	}

	/** One source into {@code v} and {@code c}; throws on a wrong shape (the caller skips the whole file). */
	private static void read(Source src, Predicate<ResourceLocation> known, Map<ResourceLocation, Double> v,
							 Map<ResourceLocation, ResourceLocation> c, int[] absent, int[] bad) {
		JsonObject root = src.json();
		if (root.has("values")) {
			for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("values").entrySet()) {
				ResourceLocation id = ResourceLocation.tryParse(e.getKey());
				if (id == null) continue;
				if (!known.test(id)) {
					absent[0]++;
					continue;
				}
				double val = e.getValue().getAsDouble();
				if (!Double.isFinite(val) || val < 0) {
					bad[0]++;
					continue;
				}
				v.put(id, val);
			}
		}
		if (root.has("families")) {
			for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("families").entrySet()) {
				JsonArray members = e.getValue().getAsJsonArray();
				if (members.size() < 2) continue;
				ResourceLocation head = ResourceLocation.tryParse(members.get(0).getAsString());
				if (head == null) continue;
				if (!known.test(head)) {
					absent[0] += members.size();
					continue;
				}
				for (JsonElement m : members) {
					ResourceLocation id = ResourceLocation.tryParse(m.getAsString());
					if (id == null || id.equals(head)) continue;
					if (!known.test(id)) {
						absent[0]++;
						continue;
					}
					c.put(id, head);
				}
			}
		}
	}

	private Diversity() {}
}
