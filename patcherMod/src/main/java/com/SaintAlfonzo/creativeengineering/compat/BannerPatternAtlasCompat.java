package com.SaintAlfonzo.creativeengineering.compat;

import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.texture.TextureAtlas;
import net.minecraft.core.Registry;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.world.level.block.entity.BannerPattern;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.client.event.TextureStitchEvent;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

/**
 * bedspreads and customizableelytra both build their per-layer banner-pattern {@code Material}
 * against the block atlas ({@code TextureAtlas.LOCATION_BLOCKS}, confirmed identical to
 * {@code InventoryMenu.BLOCK_ATLAS}) rather than the dedicated banner atlas
 * ({@code Sheets.BANNER_SHEET} / {@code textures/atlas/banner_patterns.png}) vanilla actually
 * stitches every registered pattern's real texture into.
 *
 * <p>bedspreads bundles its own hand-recentered compat texture
 * ({@code bedspreads:entity/<originNamespace>/<originPath>}) for a curated subset of mods —
 * those textures are redrawn/repositioned to land correctly on the *bed model's* UV layout
 * (which is vanilla's plain bed geometry, reused for the pattern overlay pass), not on a
 * banner flag's layout. A pattern's real {@code <namespace>:entity/banner/<path>} texture is
 * authored for the banner flag's own UV footprint and lands in an unrelated spot on the bed
 * model if used directly — see {@code BedspreadsBannerPatternMixin} for the full story.
 *
 * <p>For every registered pattern bedspreads does NOT bundle a curated texture for, this
 * stitches our own {@code creativeengineering:entity/<namespace>/<path>} compat texture
 * (generated offline by {@code tools/gen_bedspreads_pattern_compat.py}, which reproduces
 * bedspreads' own recentering convention) into the block atlas instead, so
 * {@code BedspreadsBannerPatternMixin} has somewhere correct to redirect to. Patterns with
 * neither a bedspreads nor a generated compat texture are skipped here too — their real texture
 * is authored for a banner flag's UV footprint, not this bed model's, so stitching it in would
 * just be dead atlas space {@code BedspreadsBannerPatternMixin} never points at.
 *
 * <p>Same story for customizableelytra, whose curated set
 * ({@code customizableelytra:entity/elytra_banner[_low]/<path>}, flat — no per-mod namespace
 * folder) is keyed on the pattern's bare id and covers a different, larger subset of mods. For
 * every pattern id it doesn't cover, this stitches
 * {@code creativeengineering:entity/elytra_banner[_low]/<namespace>/<path>} (generated by
 * {@code tools/gen_elytra_pattern_compat.py}, one output per resolution customizableelytra
 * supports) so {@code CustomizableElytraBannerPatternMixin} has somewhere correct to fall back
 * to.
 */
@Mod.EventBusSubscriber(modid = "creativeengineering", bus = Mod.EventBusSubscriber.Bus.MOD, value = Dist.CLIENT)
public class BannerPatternAtlasCompat {

    @SubscribeEvent
    public static void onTextureStitchPre(TextureStitchEvent.Pre event) {
        if (!event.getAtlas().location().equals(TextureAtlas.LOCATION_BLOCKS)) return;
        ResourceManager resources = Minecraft.getInstance().getResourceManager();
        for (ResourceKey<BannerPattern> key : Registry.BANNER_PATTERN.registryKeySet()) {
            ResourceLocation id = key.location();
            String relativePath = "entity/" + id.getNamespace() + "/" + id.getPath();

            // Material/sprite locations (what addSprite/Material take) are bare - the atlas
            // expands them to "textures/<path>.png" internally. ResourceManager#getResource
            // does no such expansion, so existence checks need the real file path spelled out.
            ResourceLocation bedspreadsFile = new ResourceLocation("bedspreads", "textures/" + relativePath + ".png");
            if (resources.getResource(bedspreadsFile).isPresent()) continue;

            ResourceLocation generatedTexture = new ResourceLocation("creativeengineering", relativePath);
            ResourceLocation generatedFile = new ResourceLocation("creativeengineering", "textures/" + relativePath + ".png");
            if (resources.getResource(generatedFile).isPresent()) {
                event.addSprite(generatedTexture);
            }

            for (String elytraFolder : ELYTRA_BANNER_FOLDERS) {
                ResourceLocation elytraCurated = new ResourceLocation("customizableelytra",
                        "textures/entity/" + elytraFolder + "/" + id.getPath() + ".png");
                if (resources.getResource(elytraCurated).isPresent()) continue;

                String elytraRelativePath = "entity/" + elytraFolder + "/" + id.getNamespace() + "/" + id.getPath();
                ResourceLocation elytraGeneratedFile = new ResourceLocation("creativeengineering",
                        "textures/" + elytraRelativePath + ".png");
                if (resources.getResource(elytraGeneratedFile).isPresent()) {
                    event.addSprite(new ResourceLocation("creativeengineering", elytraRelativePath));
                }
            }
        }
    }

    private static final String[] ELYTRA_BANNER_FOLDERS = {"elytra_banner", "elytra_banner_low"};
}
